def convert_method(src, recv, method, params, results, fields):
    # Extract "func (b *Recv) Method(params) (results) { ... }".
    pat = re.compile(
        r"^func \(([^)]+) \*?" + recv + r"\) " + method + r"\(" + re.escape(params) + r"\) \(.*?^}\n",
        re.M | re.S,
    )
    m = pat.search(src)
    assert m, f"method {recv}.{method} not found"
    body = m.group(0)
    # Extract the body between { and }.
    brace = body.index("{")
    inner = body[brace + 1 : -2]  # strip "{\n" and "\n}\n"
    recv_var = m.group(1)
    # Build the helper.
    pair_name = f"__bufio{recv}{method}Pair"
    helper_name = f"__bufio{recv}{method}"
    pair_def = f"type {pair_name} struct {{\n"
    for f in fields:
        pair_def += f"\t{f} interface{{}}\n"  # placeholder, fix types below
    pair_def += "}\n\n"
    # Actually, use proper types from results. Simplified: we'll write
    # the pair manually for each method below.
    return src, (recv, method, params, results, fields, recv_var, inner)


