def strip_imports(src):
    src = re.sub(r'^import \(\n(?:.*\n)*?^\)\n', '', src, count=1, flags=re.M)
    src = re.sub(r'^import "[^"]*"\n', '', src, flags=re.M)
    return src


def strip_package(src):
    return re.sub(r"^package bufio\n", "", src, count=1, flags=re.M)


def replace_utf8(src):
    # Replace utf8.X with __bufioX.
    src = src.replace("utf8.DecodeRune", "__bufioDecodeRune")
    src = src.replace("utf8.EncodeRune", "__bufioEncodeRune")
    src = src.replace("utf8.FullRune", "__bufioFullRune")
    src = src.replace("utf8.RuneError", "__bufioRuneError")
    src = src.replace("utf8.RuneSelf", "__bufioRuneSelf")
    src = src.replace("utf8.UTFMax", "__bufioUTFMax")
    src = src.replace("utf8.MaxRune", "__bufioMaxRune")
    src = src.replace("utf8.RuneCountInString", "__bufioRuneCountInString")
    return src


