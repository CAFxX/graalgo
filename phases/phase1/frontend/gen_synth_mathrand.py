# Sections of rand.go to drop (replaced by the header's deviations):
# - the import block (rewritten in the header)
# - "var globalRandGenerator atomic.Pointer[Rand]"
# - "var randautoseed = godebug.New(...)" / "var randseednop = ..."
# - "func globalRand() *Rand { ... }" (full function)
# - "//go:linkname runtime_rand runtime.rand\nfunc runtime_rand() uint64"
# - "func Seed(seed int64) { ... }" (full function, rewritten)


def strip_imports(src):
    src = re.sub(r'^import \(\n(?:.*\n)*?^\)\n', '', src, count=1, flags=re.M)
    src = re.sub(r'^import "[^"]*"\n', '', src, flags=re.M)
    src = re.sub(r'^import _ "[^"]*"( //.*)?\n', '', src, flags=re.M)
    return src


def strip_globalRandGenerator(src):
    src = src.replace("var globalRandGenerator atomic.Pointer[Rand]\n", "")
    src = src.replace('var randautoseed = godebug.New("randautoseed")\n', "")
    src = src.replace('var randseednop = godebug.New("randseednop")\n', "")
    return src


def strip_func(src, name):
    # Remove "func name(...) ... \n}\n" (top-level, brace at column 0).
    pat = re.compile(r"^func " + name + r"\(.*?^}\n", re.M | re.S)
    src, n = pat.subn("", src, count=1)
    assert n == 1, f"strip_func {name}: {n}"
    return src


SEED_NEW = '''// Seed uses the provided seed value to initialize the default Source to a
// deterministic state.
//
// As of Go 1.24 [Seed] is a no-op (unless GODEBUG=randseednop=0, which
// the frontend stub does not observe; see header deviation 1).
func Seed(seed int64) {
	if randseednop.Value() != "0" {
		return
	}
	randseednop.IncNonDefault()

	// P3-M9 deviation 2: mutex-guarded instead of atomic.Pointer CAS.
	globalRandMu.Lock()
	defer globalRandMu.Unlock()
	orig := globalRandGen

	// If we are already using a lockedSource, we can just re-seed it.
	if orig != nil {
		if _, ok := orig.src.(*lockedSource); ok {
			orig.Seed(seed)
			return
		}
	}

	r := New(new(lockedSource))
	r.Seed(seed)
	globalRandGen = r
}

'''


def build_rand_go():
    with open(f"{GOROOT}/rand.go") as f:
        src = f.read()
    src = re.sub(r"^package rand\n", "", src, count=1, flags=re.M)
    src = strip_imports(src)
    src = strip_globalRandGenerator(src)
    src = strip_func(src, "globalRand")
    # Drop the linkname decl of runtime_rand (header provides the impl).
    src = src.replace(
        '//go:linkname runtime_rand runtime.rand\nfunc runtime_rand() uint64\n', ""
    )
    src = strip_func(src, "Seed")
    # Deviation: sync.Mutex as struct field is not in M2 scope. Remove
    # mutex fields (single-threaded; the port is not thread-safe).
    src = src.replace(
        "\t// The mutex is used to avoid race conditions in Read.\n\tmu sync.Mutex\n",
        "\t// P3-M9: mutex removed (not in M2 scope; single-threaded).\n",
    )
    # lockedSource lk field.
    src = re.sub(
        r"\tlk sync\.Mutex\n",
        "\t// P3-M9: mutex removed (not in M2 scope; single-threaded).\n",
        src,
    )
    # Remove Lock/Unlock calls.
    src = re.sub(r"\n\t\w+\.mu\.Lock\(\)", "", src)
    src = re.sub(r"\n\t\w+\.mu\.Unlock\(\)", "", src)
    src = re.sub(r"\n\t\w+\.lk\.Lock\(\)", "", src)
    src = re.sub(r"\n\t\w+\.lk\.Unlock\(\)", "", src)
    src = src.replace("fs.mu.Lock()\n", "")
    src = src.replace("fs.mu.Unlock()\n", "")
    # Fix implicit address-of: use pointer from start (WS D limitation:
    # no & on Ident, no implicit address-of).
    src = src.replace(
        "\tvar rng rngSource\n\trng.Seed(seed)\n\treturn &rng",
        "\trng := new(rngSource)\n\trng.Seed(seed)\n\treturn rng",
    )
    # Fix & on SelectorExpr: inline seedPos (mutexes removed, so it's just seed + reset).
    src = src.replace(
        "\tif lk, ok := r.src.(*lockedSource); ok {\n\t\tlk.seedPos(seed, &r.readPos)\n\t\treturn\n\t}",
        "\tif lk, ok := r.src.(*lockedSource); ok {\n\t\t// P3-M9: seedPos inlined (mutex removed; WS D: no & on SelectorExpr).\n\t\tlk.seed(seed)\n\t\tr.readPos = 0\n\t\treturn\n\t}",
    )
    # Fix & on SelectorExpr in Read: refactor read() to be a method on *Rand
    # returning a pair (frontend doesn't support 2-result method definitions).
    # Define the pair type first (needed by readBuf).
    src = src.replace(
        "func read(p []byte, src Source, readVal *int64, readPos *int8) (n int, err error) {",
        "// P3-M9: __randReadPair defined here (used by readBuf and __randRead).\ntype __randReadPair struct {\n\tn   int\n\terr error\n}\n\nfunc (r *Rand) readBuf(p []byte, src Source) __randReadPair {",
    )
    src = src.replace(
        "\tpos := *readPos\n\tval := *readVal\n",
        "\tvar n int\n\tvar err error\n\tpos := r.readPos\n\tval := r.readVal\n",
        1,  # only first occurrence (in readBuf)
    )
    src = src.replace(
        "\t*readPos = pos\n\t*readVal = val\n\treturn\n}",
        "\tr.readPos = pos\n\tr.readVal = val\n\treturn __randReadPair{n: n, err: err}\n}",
        1,  # only first occurrence
    )
    # Update call sites.
    src = src.replace(
        "\t\treturn src.read(p, &r.readVal, &r.readPos)\n\tcase *runtimeSource:\n\t\treturn src.read(p, &r.readVal, &r.readPos)\n\t}\n\treturn read(p, r.src, &r.readVal, &r.readPos)",
        "\t\treturn r.readBuf(p, src)\n\tcase *runtimeSource:\n\t\treturn r.readBuf(p, src)\n\t}\n\treturn r.readBuf(p, r.src)",
    )
    # Fix runtimeSource.read and lockedSource.read methods: they're now unused
    # (Rand.Read calls r.readBuf). Remove them to avoid undefined 'read'.
    src = re.sub(
        r"\nfunc \(fs \*runtimeSource\) read\(p \[\]byte, readVal \*int64, readPos \*int8\) \(n int, err error\) \{\n\tn, err = read\(p, fs, readVal, readPos\)\n\treturn\n\}",
        "\n// P3-M9: runtimeSource.read removed (Rand.Read uses r.readBuf; mutex removed).",
        src,
    )
    src = re.sub(
        r"\n// read implements Read for a lockedSource without a race condition\.\nfunc \(r \*lockedSource\) read\(p \[\]byte, readVal \*int64, readPos \*int8\) \(n int, err error\) \{\n\tn, err = read\(p, r\.s, readVal, readPos\)\n\treturn\n\}",
        "\n// P3-M9: lockedSource.read removed (Rand.Read uses r.readBuf; mutex removed).",
        src,
    )
    # Deviation: Float32 removed (frontend has no float32 value support;
    # FuncValueCallNode kind FLOAT32 has no float value). Documented.
    src = re.sub(
        r"\n// Float32 returns, as a float32, a pseudo-random number in \[0\.0,1\.0\)[^\n]*\nfunc \(r \*Rand\) Float32\(\) float32 \{[^\n]*\n\}[^\n]*\n",
        "\n// P3-M9: Float32 removed (frontend/v1 has no float32 value support).\n",
        src,
    )
    # Remove seedPos method (inlined into Rand.Seed; uses *readPos assignment
    # which is WS D-limited: "assignment to *ast.StarExpr is not supported").
    src = re.sub(
        r"\n// seedPos implements Seed for a lockedSource without a race condition\.\nfunc \(r \*lockedSource\) seedPos\(seed int64, readPos \*int8\) \{\n\tr\.seed\(seed\)\n\t\*readPos = 0\n\}",
        "\n// P3-M9: seedPos removed (inlined into Rand.Seed; WS D: no *ptr assignment).",
        src,
    )
    # Appendix M for Rand.Read (2-result method): extract the real implementation
    # into __randRead, replace Read with a panic stub.
    # Note: __randReadPair type is already defined above (for readBuf).
    # Find the Read method body.
    read_pat = r"\nfunc \(r \*Rand\) Read\(p \[\]byte\) \(n int, err error\) \{(.*?)\n\}\n"
    m = re.search(read_pat, src, re.S)
    if m:
        body = m.group(1)
        # The body now calls r.readBuf which returns __randReadPair directly.
        # No transformation needed.
        # Create the helper with the real body (pair type already defined).
        helper = f"\n// P3-M9 (tier1c): Appendix M for Rand.Read (real implementation).\nfunc __randRead(r *Rand, p []byte) __randReadPair {{{body}\n}}\n"
        # Replace the original with a stub.
        stub = "\n// P3-M9: Rand.Read is a stub; calls are desugared to __randRead (Appendix M).\nfunc (r *Rand) Read(p []byte) (n int, err error) {\n\tpanic(\"math/rand: Read: multi-result call needs the Appendix M desugar\")\n}\n"
        src = src.replace(m.group(0), helper + stub, 1)
    # Insert the rewritten Seed after the runtimeSource.read method
    # (i.e. right before the "/* Top-level convenience functions */"
    # comment block, which we keep).
    anchor = "/*\n * Top-level convenience functions\n */\n"
    assert anchor in src
    src = src.replace(anchor, SEED_NEW + anchor, 1)
    return src


def build_file(name, extra_import=None):
    with open(f"{GOROOT}/{name}") as f:
        src = f.read()
    src = re.sub(r"^package rand\n", "", src, count=1, flags=re.M)
    src = strip_imports(src)
    return src


def main():
    parts = [HEADER]
    parts.append(build_rand_go().rstrip() + "\n\n")
    for name in ["rng.go", "exp.go", "normal.go", "zipf.go"]:
        parts.append(build_file(name).rstrip() + "\n\n")
    out = "".join(parts).rstrip() + "\n`\n"
    with open("/home/hatch/workspace/graalgo-m9/phases/phase1/frontend/synth_mathrand.go", "w") as f:
        f.write(out)
    print("wrote synth_mathrand.go", len(out), "bytes")


main()
