// shiftMask is a no-op shift mask for x86-64.
// Using it lets the compiler omit the check for shift size >= 64.
const reg8SizeMask64 = 63

type __flateCompressorfindMatchPair struct {
	length int32
	offset int32
	ok bool
}

func __flateCompressorfindMatch(d *compressor, pos int32, prevHead int32, lookahead int32) __flateCompressorfindMatchPair {
	var length int32
	var offset int32
	var ok bool

	minMatchLook := __flateMinInt32(lookahead, maxMatchLength)

	win := d.window[0 : pos+minMatchLook]

	// We quit when we get a match that's at least nice long
	nice := __flateMinInt32(d.nice, int32(len(win))-pos)

	// If we've got a match that's good enough, only look in 1/4 the chain.
	tries := d.chain
	length = minMatchLength - 1

	wEnd := win[pos+length]
	wPos := win[pos:]
	minIndex := __flateMaxInt32(pos-windowSize, 0)
	offset = 0

	// Minimum gain to accept a match.
	cGain := 4

	// Some like it higher (CSV), some like it lower (JSON)
	const baseCost = 3
	// Base is 4 bytes at with an additional cost.
	// Matches must be better than this.

	for i := prevHead; tries > 0; tries-- {
		if wEnd == win[i+length] {
			n := int32(matchLen(win[i:i+minMatchLook], wPos))
			if n > length {
				if d.chain >= 100 {
					// Calculate gain. Estimates the gains of the new match compared to emitting as literals.
					newGain := d.h.bitLengthRaw(wPos[:n]) - int(offsetExtraBits[offsetCode(uint32(pos-i))]) - baseCost - int(lengthExtraBits[lengthCodes[(n-3)&255]])
					if newGain <= cGain {
						goto next
					}
					cGain = newGain
				}
				length = n
				offset = pos - i
				ok = true
				if n >= nice {
					// The match is good enough that we don't try to find a better one.
					break
				}
				wEnd = win[pos+n]
			}
		}
	next:
		if i <= minIndex {
			// hashPrev[i & windowMask] has already been overwritten, so stop now.
			break
		}
		i = d.state.hashPrev[i&windowMask] - d.state.hashOffset
		if i < minIndex {
			break
		}
	}
	return __flateCompressorfindMatchPair{length: length, offset: offset, ok: ok}
}

type __flateCompressortryBetterMatchAtEndPair struct {
	newLen int32
	newOff int32
}

func __flateCompressortryBetterMatchAtEnd(d *compressor, prevLength, prevOffset, lookahead int32) __flateCompressortryBetterMatchAtEndPair {

	// We start checking at checkOff from the current match position.
	// This allows up to two additional literals, but that could be
	// compensated by a higher quality match.
	// If the match looks better, we extend backwards.
	const checkOff = 2
	s := d.state

	if prevLength >= maxMatchLength-checkOff {
		return __flateCompressortryBetterMatchAtEndPair{newLen: prevLength, newOff: prevOffset}
	}
	prevIndex := s.index - 1
	if prevIndex+prevLength >= s.maxInsertIndex {
		return __flateCompressortryBetterMatchAtEndPair{newLen: prevLength, newOff: prevOffset}
	}

	end := __flateMinInt32(lookahead, maxMatchLength+checkOff) + prevIndex
	minIndex := __flateMaxInt32(s.index-windowSize, 0)

	h := hash4(d.window[prevIndex+prevLength:])
	ch2 := s.hashHead[h] - s.hashOffset - prevLength
	if prevIndex-ch2 == prevOffset || ch2 <= minIndex+checkOff {
		return __flateCompressortryBetterMatchAtEndPair{newLen: prevLength, newOff: prevOffset}
	}

	length := int32(matchLen(d.window[prevIndex+checkOff:end], d.window[ch2+checkOff:]))
	if length <= prevLength {
		return __flateCompressortryBetterMatchAtEndPair{newLen: prevLength, newOff: prevOffset}
	}

	prevLength = length
	prevOffset = prevIndex - ch2

	for i := int32(checkOff - 1); i >= 0; i-- {
		if prevLength >= maxMatchLength || d.window[prevIndex+i] != d.window[ch2+i] {
			for j := range i + 1 {
				d.tokens.AddLiteral(d.window[prevIndex+j])
				if d.tokens.n == maxFlateBlockTokens {
					if d.err = d.writeBlock(d.tokens, s.index, false); d.err != nil {
						return __flateCompressortryBetterMatchAtEndPair{newLen: prevLength, newOff: prevOffset}
					}
					d.tokens.Reset()
				}
				s.index++
				if s.index < s.maxInsertIndex {
					h := hash4(d.window[s.index:])
					ch := s.hashHead[h]
					s.chainHead = ch
					s.hashPrev[s.index&windowMask] = ch
					s.hashHead[h] = s.index + s.hashOffset
				}
			}
			break
		}
		prevLength++
	}
	return __flateCompressortryBetterMatchAtEndPair{newLen: prevLength, newOff: prevOffset}
}

type __flateCompressorwritePair struct {
	n int
	err error
}

func __flateCompressorwrite(d *compressor, b []byte) __flateCompressorwritePair {
	var n int

	if d.err != nil {
		return __flateCompressorwritePair{n: 0, err: d.err}
	}
	n = len(b)
	for len(b) > 0 {
		if int(d.windowEnd) == len(d.window) || d.sync {
			__flateCompressorStep(d)
		}
		b = b[__flateCompressorFill(d, b):]
		if d.err != nil {
			return __flateCompressorwritePair{n: 0, err: d.err}
		}
	}
	return __flateCompressorwritePair{n: n, err: d.err}
}

