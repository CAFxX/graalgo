func __flateDecompressorRead(f *decompressor, b []byte) __flateDecompressorReadPair {

	for {
		if len(f.toRead) > 0 {
			n := copy(b, f.toRead)
			f.toRead = f.toRead[n:]
			if len(f.toRead) == 0 {
				return __flateDecompressorReadPair{n: n, err: f.err}
			}
			return __flateDecompressorReadPair{n: n, err: nil}
		}
		if f.err != nil {
			return __flateDecompressorReadPair{n: 0, err: f.err}
		}
		__flateDecompressorStep(f)
		if f.err != nil && len(f.toRead) == 0 {
			f.toRead = f.dict.readFlush() // Flush what's left in case of error
		}
	}
}

