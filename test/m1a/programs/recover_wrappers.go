package main

// recover() through generated wrapper frames (GG-0070): a method value, a method
// expression, an interface method value and a method promoted from an embedded
// interface are called through wrappers that gc marks WRAPPER, so the method
// they forward to is still "called directly by the deferred function" and its
// recover() stops the panic.

type T struct{ name string }

func (t T) M() {
	println(t.name, "recovered", recover() != nil)
}

func (t *T) P() {
	println(t.name, "ptr recovered", recover() != nil)
}

type R interface{ M() }

type Outer struct{ R }

type Embeds struct{ T }

type EmbedsPtr struct{ *T }

func methodValue() {
	f := T{"value"}.M
	defer f()
	panic(1)
}

func ptrMethodValue() {
	t := &T{"ptrvalue"}
	defer t.P()
	f := t.P
	defer f()
	panic(2)
}

func methodExpr() {
	defer T.M(T{"expr"})
	panic(3)
}

func ptrMethodExpr() {
	defer (*T).P(&T{"ptrexpr"})
	panic(4)
}

func ifaceMethodValue() {
	var r R = T{"ifacevalue"}
	f := r.M
	defer f()
	panic(5)
}

func ifaceMethodExpr() {
	defer R.M(T{"ifaceexpr"})
	panic(6)
}

func embeddedIface() {
	o := Outer{T{"embedded"}}
	defer o.M()
	panic(7)
}

func embeddedIfaceValue() {
	var r R = Outer{T{"embeddedvalue"}}
	f := r.M
	defer f()
	panic(8)
}

// Methods promoted from an embedded struct (gc: autogenerated wrappers).
func embeddedStruct() {
	var r R = Embeds{T{"embeddedstruct"}}
	defer r.M()
	panic(10)
}

func embeddedStructValue() {
	f := Embeds{T{"embeddedstructvalue"}}.M
	defer f()
	panic(11)
}

func embeddedPtr() {
	var r R = EmbedsPtr{&T{"embeddedptr"}}
	defer r.M()
	panic(12)
}

func embeddedPtrExpr() {
	defer EmbedsPtr.P(EmbedsPtr{&T{"embeddedptrexpr"}})
	panic(13)
}

// A wrapper called by a function that is not deferred is not eligible.
func indirect() {
	defer func() {
		f := T{"indirect"}.M
		f()
		println("indirect recovered", recover() != nil)
	}()
	panic(9)
}

// Outside a panic a wrapped recover returns nil.
func noPanic() {
	f := T{"nopanic"}.M
	defer f()
}

func main() {
	methodValue()
	ptrMethodValue()
	methodExpr()
	ptrMethodExpr()
	ifaceMethodValue()
	ifaceMethodExpr()
	embeddedIface()
	embeddedIfaceValue()
	embeddedStruct()
	embeddedStructValue()
	embeddedPtr()
	embeddedPtrExpr()
	indirect()
	noPanic()
	println("done")
}
