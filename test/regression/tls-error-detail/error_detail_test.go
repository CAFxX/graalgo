func serverConfig() *tls.Config {
	cert, err := tls.X509KeyPair([]byte(srvPEM), []byte(srvKeyPEM))
	if err != nil {
		panic("X509KeyPair: " + err.Error())
	}
	return &tls.Config{
		Certificates: []tls.Certificate{cert},
		MinVersion:   tls.VersionTLS12,
		MaxVersion:   tls.VersionTLS12,
	}
}

func mismatchClientConfig() *tls.Config {
	caBlock, _ := pem.Decode([]byte(caPEM))
	ca, err := x509.ParseCertificate(caBlock.Bytes)
	if err != nil {
		panic("parse ca: " + err.Error())
	}
	roots := x509.NewCertPool()
	roots.AddCert(ca)
	return &tls.Config{
		RootCAs:    roots,
		ServerName: "localhost",
		MinVersion: tls.VersionTLS13,
		MaxVersion: tls.VersionTLS13,
	}
}

func matchingClientConfig() *tls.Config {
	cfg := mismatchClientConfig()
	cfg.MinVersion = tls.VersionTLS12
	cfg.MaxVersion = tls.VersionTLS13
	return cfg
}

func TestEngineFailureSurfacedWithDetail(t *testing.T) {
	ln, err := tls.Listen("tcp", "127.0.0.1:0", serverConfig())
	if err != nil {
		t.Fatalf("tls.Listen: %v", err)
	}
	defer ln.Close()
	serverErr := make(chan error, 1)
	go func() {
		conn, err := ln.Accept()
		if err != nil {
			serverErr <- err
			return
		}
		defer conn.Close()
		serverErr <- conn.(*tls.Conn).Handshake()
	}()
	conn, err := net.Dial("tcp", ln.Addr().String())
	if err != nil {
		t.Fatalf("net.Dial: %v", err)
	}
	defer conn.Close()
	tlsConn := tls.Client(conn, mismatchClientConfig())
	if err := tlsConn.Handshake(); err == nil {
		t.Fatalf("client Handshake() = nil, want error (version mismatch)")
	}
	serr := <-serverErr
	if serr == nil {
		t.Fatalf("server Handshake() = nil, want error (version mismatch)")
	}
	if !strings.Contains(serr.Error(), "wrap failed") {
		t.Fatalf("server Handshake() = %v, want error containing %q", serr, "wrap failed")
	}
	// P1-B4: the Java exception must survive to the Go error value, not
	// just the bare sentinel message.
	if !strings.Contains(serr.Error(), "SSLHandshakeException") {
		t.Fatalf("server Handshake() = %v, want error naming the Java exception %q", serr, "SSLHandshakeException")
	}
}

func TestCleanCloseIsNotATlsFailure(t *testing.T) {
	ln, err := tls.Listen("tcp", "127.0.0.1:0", serverConfig())
	if err != nil {
		t.Fatalf("tls.Listen: %v", err)
	}
	defer ln.Close()
	serverDone := make(chan struct{})
	go func() {
		defer close(serverDone)
		conn, err := ln.Accept()
		if err != nil {
			return
		}
		defer conn.Close()
		if err := conn.(*tls.Conn).Handshake(); err != nil {
			t.Errorf("server Handshake(): %v", err)
			return
		}
		// Close immediately after a successful handshake: no engine
		// failure is recorded on either side for this connection.
	}()
	conn, err := net.Dial("tcp", ln.Addr().String())
	if err != nil {
		t.Fatalf("net.Dial: %v", err)
	}
	defer conn.Close()
	tlsConn := tls.Client(conn, matchingClientConfig())
	if err := tlsConn.Handshake(); err != nil {
		t.Fatalf("client Handshake(): %v", err)
	}
	<-serverDone
	buf := make([]byte, 64)
	_, rerr := tlsConn.Read(buf)
	if rerr == nil {
		t.Fatalf("client Read after server close = nil, want an error (EOF or transport close)")
	}
	if strings.Contains(rerr.Error(), "failed") {
		t.Fatalf("client Read after clean close = %v, want no TLS failure (stale engine-failure record?)", rerr)
	}
	if rerr != io.EOF {
		t.Logf("client Read after server close = %v (transport close, not a TLS failure)", rerr)
	}
}
