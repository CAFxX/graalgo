// Regression test for REVIEW-2026-11-03-16 P1-B4 (tls error swallowing):
// TlsRuntime.wrap/unwrap used to catch every exception and return null,
// the same sentinel as a clean peer close, discarding the exception.
// The Go side now resolves every nil wrap/unwrap result through the
// graalgo.tls.lastError trap: a recorded engine failure surfaces as a Go
// error carrying the Java exception, while a clean close still reads as
// EOF. This test pins both halves through the public crypto/tls API:
//
//   - a version-mismatch handshake (TLS 1.3-only client vs TLS 1.2-only
//     server) makes the server's SSLEngine.wrap() throw
//     SSLHandshakeException: the server Handshake() error must carry
//     both "wrap failed" and the exception class. Pre-fix it was the
//     bare "tls: wrap failed" (or, before the tls-wrap-hang fix, nil).
//   - a clean close after a successful handshake must NOT surface as a
//     TLS failure: the client's Read must not report any "failed" error
//     (no stale engine-failure record may leak into the Read path).
//
// Cert fixtures copied verbatim from test/corpus/wave3/crypto/tls/01_handshake.go
// (via test/regression/tls-wrap-hang/mismatch_test.go).
