func TestMislabeledPkcs8Rejected(t *testing.T) {
	if _, err := x509.ParsePKCS8PrivateKey(pkcs8K1); err == nil {
		t.Fatal("ParsePKCS8PrivateKey accepted secp256k1-relabeled P-256 key, gc rejects")
	}
}

func TestMislabeledSpkiRejected(t *testing.T) {
	if _, err := x509.ParsePKIXPublicKey(spkiK1); err == nil {
		t.Fatal("ParsePKIXPublicKey accepted secp256k1-relabeled P-256 key, gc rejects")
	}
}

func TestMislabeledCertRejected(t *testing.T) {
	if _, err := x509.ParseCertificate(certK1); err == nil {
		t.Fatal("ParseCertificate accepted secp256k1-relabeled P-256 cert, gc rejects")
	}
}

func TestValidFormsAccepted(t *testing.T) {
	priv, err := x509.ParsePKCS8PrivateKey(pkcs8Valid)
	if err != nil {
		t.Fatalf("ParsePKCS8PrivateKey valid P-256: %v", err)
	}
	ec, ok := priv.(*ecdsa.PrivateKey)
	if !ok || ec.Curve.Params().Name != "P-256" {
		t.Fatalf("valid PKCS#8 did not parse to a P-256 key: %T", priv)
	}
	pub, err := x509.ParsePKIXPublicKey(spkiValid)
	if err != nil {
		t.Fatalf("ParsePKIXPublicKey valid P-256: %v", err)
	}
	ecPub, ok := pub.(*ecdsa.PublicKey)
	if !ok || ecPub.Curve.Params().Name != "P-256" {
		t.Fatalf("valid SPKI did not parse to a P-256 key: %T", pub)
	}
	cert, err := x509.ParseCertificate(certValid)
	if err != nil {
		t.Fatalf("ParseCertificate valid P-256: %v", err)
	}
	certPub, ok := cert.PublicKey.(*ecdsa.PublicKey)
	if !ok || certPub.Curve.Params().Name != "P-256" {
		t.Fatalf("valid cert did not parse to a P-256 key: %T", cert.PublicKey)
	}
}
