def main():
    if os.listdir(OUTDIR):
        print("requirements/ not empty; refusing to double-mint", file=sys.stderr)
        sys.exit(1)
    env = dict(os.environ, PATH=os.path.expanduser("~/tools/go/bin") + ":" + os.environ.get("PATH", ""))
    for i, (title, stmt, rat, vp) in enumerate(REQS, start=1):
        cmd = ["go", "run", ".", "add",
               "--title", title, "--statement", stmt,
               "--rationale", rat, "--verification-plan", vp,
               "--root", ROOT]
        r = subprocess.run(cmd, cwd=REQDIR, env=env, capture_output=True, text=True)
        if r.returncode != 0:
            print(f"FAILED at index {i} ({title}): {r.stderr}", file=sys.stderr)
            sys.exit(1)
        print(r.stdout.strip(), flush=True)
    print(f"minted {len(REQS)} requirements")

if __name__ == "__main__":
    main()
