package schema

import (
	"fmt"
	"go/format"
	"strings"
)

// goName is the Go type name of a union member: Member + Union, as go/ast
// names its nodes (ConstExpr, IfStmt, StructType).
func goMemberName(u *Union, m *Member) string { return m.Name + u.Name }

func (s *Schema) goType(t *Type) string {
	switch t.Kind {
	case Prim:
		return map[string]string{"uint": "uint64", "int": "int64", "bool": "bool", "bytes": "[]byte", "str": "string"}[t.Name]
	case Ref:
		switch t.Name {
		case "type":
			return "TypeID"
		case "pos":
			return "PosID"
		}
		return "uint32"
	case OptRef:
		return "int32"
	case EnumT, UnionT, OptUnion:
		return t.Name
	case RecordT:
		return t.Name
	case OptRecord:
		return "*" + t.Name
	case List:
		return "[]" + s.goType(t.Elem)
	}
	panic("unreachable")
}

// GenerateGo returns the source of ir/gir_gen.go.
func (s *Schema) GenerateGo() ([]byte, error) {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p("// Code generated by ir/gen from schema.txt; DO NOT EDIT.\n\npackage ir\n\nimport \"fmt\"\n\n")
	p("// SchemaVersion is the `version` of schema.txt.\nconst SchemaVersion = %d\n\n", s.Version)
	p("// MaxDepth bounds node nesting (schema.txt maxdepth): deeper input is\n// rejected, so that a recursive decoder cannot exhaust its stack.\nconst MaxDepth = %d\n\n", s.MaxDepth)
	p("// SchemaHash identifies schema.txt; it is part of every GIR header.\nvar SchemaHash = [8]byte{")
	for i, c := range s.Hash {
		if i > 0 {
			p(", ")
		}
		p("0x%02x", c)
	}
	p("}\n\n")

	for _, e := range s.Enums {
		p("type %s uint8\n\nconst (\n", e.Name)
		for _, v := range e.Values {
			if v.Comment != "" {
				p("\t// %s\n", v.Comment)
			}
			p("\t%s%s %s = %d\n", e.Name, v.Name, e.Name, v.Value)
		}
		p(")\n\nfunc (v %s) Valid() bool {\n\tswitch v {\n\tcase ", e.Name)
		for i, v := range e.Values {
			if i > 0 {
				p(", ")
			}
			p("%s%s", e.Name, v.Name)
		}
		p(":\n\t\treturn true\n\t}\n\treturn false\n}\n\n")
		p("func (v %s) String() string {\n\tswitch v {\n", e.Name)
		for _, v := range e.Values {
			p("\tcase %s%s:\n\t\treturn %q\n", e.Name, v.Name, v.Name)
		}
		p("\t}\n\treturn \"%s(?)\"\n}\n\n", e.Name)
	}

	for _, r := range s.Records {
		p("type %s struct {\n", r.Name)
		for _, f := range r.Fields {
			p("\t%s %s\n", exported(f.Name), s.goType(f.Type))
		}
		p("}\n\n")
	}
	for _, u := range s.Unions {
		p("// %s is a node of the %s union.\ntype %s interface {\n\t// Tag is the member's kind number on the wire.\n\tUnionTag() int\n\tis%s()\n}\n\n", u.Name, u.Name, u.Name, u.Name)
		p("// %sKindNames maps a %s kind to its member name.\nvar %sKindNames = map[int]string{\n", u.Name, u.Name, u.Name)
		for _, m := range u.Members {
			p("\t%d: %q,\n", m.Kind, m.Name)
		}
		p("}\n\n")
		for _, m := range u.Members {
			n := goMemberName(u, m)
			p("type %s struct {\n", n)
			for _, f := range m.Fields {
				p("\t%s %s\n", exported(f.Name), s.goType(f.Type))
			}
			p("}\n\nfunc (*%s) UnionTag() int { return %d }\nfunc (*%s) is%s() {}\n\n", n, m.Kind, n, u.Name)
		}
	}

	// File
	p("// File is one decoded GIR file. Bodies[i] is the decoded body of\n// Funcs[i] (nil while not decoded, and for bodyless functions).\ntype File struct {\n\tGoVersion, GOOS, GOARCH string\n")
	for _, sec := range s.Sections {
		if sec.Raw {
			continue
		}
		p("\t%s %s\n", exported(sec.Field), s.goType(sec.Type))
	}
	p("\tBodies []*FuncBody\n\tData []byte\n\n\tbodies []byte\n\tstrings []string\n\tcounts [4]int\n}\n\n")

	// Section ids
	p("const (\n")
	for _, sec := range s.Sections {
		p("\tsec%s = %d\n", sec.Name, sec.ID)
	}
	p(")\n\n// sectionIDs lists every section in wire order.\nvar sectionIDs = []int{")
	for i, sec := range s.Sections {
		if i > 0 {
			p(", ")
		}
		p("sec%s", sec.Name)
	}
	p("}\n\nvar sectionNames = map[int]string{\n")
	for _, sec := range s.Sections {
		p("\tsec%s: %q,\n", sec.Name, sec.Name)
	}
	p("}\n\n")
	// reference targets
	p("// refSections maps a reference kind to the section it indexes.\nvar refSections = map[refKind]int{\n")
	for _, k := range []string{"type", "sym", "obj", "fn"} {
		p("\tref%s: sec%s,\n", exported(k), RefSections[k])
	}
	p("}\n\n")

	// typed section codecs
	p("func (w *Writer) writeTypedSection(f *File, id int) {\n\tswitch id {\n")
	for _, sec := range s.Sections {
		if sec.Raw {
			continue
		}
		p("\tcase sec%s:\n", sec.Name)
		s.goWrite(p, sec.Type, "f."+exported(sec.Field), 2)
	}
	p("\tdefault:\n\t\tpanic(\"not a typed section\")\n\t}\n}\n\n")
	p("func (r *Reader) readTypedSection(f *File, id int) {\n\tswitch id {\n")
	for _, sec := range s.Sections {
		if sec.Raw {
			continue
		}
		p("\tcase sec%s:\n", sec.Name)
		s.goRead(p, sec.Type, "f."+exported(sec.Field), 2, 0)
	}
	p("\tdefault:\n\t\tpanic(\"not a typed section\")\n\t}\n}\n\n")

	for _, r := range s.Records {
		p("func (w *Writer) write%s(v *%s) {\n", r.Name, r.Name)
		for _, f := range r.Fields {
			s.goWrite(p, f.Type, "v."+exported(f.Name), 1)
		}
		p("}\n\n")
		p("func (r *Reader) read%s(v *%s) {\n", r.Name, r.Name)
		if r.Scope {
			p("\tr.pushScope()\n\tdefer r.popScope()\n")
		}
		for _, f := range r.Fields {
			s.goRead(p, f.Type, "v."+exported(f.Name), 1, 0)
			if r.Scope {
				switch f.Name {
				case "positions":
					p("\tr.scope().npos = len(v.Positions)\n")
				case "locals":
					p("\tr.scope().nlocals = len(v.Locals)\n")
				case "labels":
					p("\tr.scope().nlabels = len(v.Labels)\n")
				}
			}
		}
		p("}\n\n")
	}
	for _, u := range s.Unions {
		p("func (w *Writer) write%s(x %s) {\n\tw.enter()\n\tdefer w.leave()\n\tswitch v := x.(type) {\n", u.Name, u.Name)
		for _, m := range u.Members {
			p("\tcase *%s:\n\t\tw.uvarint(%d)\n", goMemberName(u, m), m.Kind)
			for _, f := range m.Fields {
				s.goWrite(p, f.Type, "v."+exported(f.Name), 2)
			}
		}
		p("\tdefault:\n\t\tpanic(fmt.Sprintf(\"ir: cannot encode %%T as %s\", x))\n\t}\n}\n\n", u.Name)
		p("func (w *Writer) writeOpt%s(x %s) {\n\tif x == nil {\n\t\tw.uvarint(0)\n\t\treturn\n\t}\n\tw.write%s(x)\n}\n\n", u.Name, u.Name, u.Name)
		p("func (r *Reader) read%s() %s {\n\treturn r.read%sKind(r.uvarint())\n}\n\n", u.Name, u.Name, u.Name)
		p("func (r *Reader) readOpt%s() %s {\n\tk := r.uvarint()\n\tif k == 0 {\n\t\treturn nil\n\t}\n\treturn r.read%sKind(k)\n}\n\n", u.Name, u.Name, u.Name)
		p("func (r *Reader) read%sKind(k uint64) %s {\n\tr.enter()\n\tdefer r.leave()\n\tswitch k {\n", u.Name, u.Name)
		for _, m := range u.Members {
			p("\tcase %d:\n\t\tv := &%s{}\n", m.Kind, goMemberName(u, m))
			for _, f := range m.Fields {
				s.goRead(p, f.Type, "v."+exported(f.Name), 2, 0)
			}
			p("\t\treturn v\n")
		}
		p("\t}\n\tr.failf(\"bad %s kind %%d\", k)\n\treturn nil\n}\n\n", u.Name)
	}
	src := b.String()
	out, err := format.Source([]byte(src))
	if err != nil {
		return []byte(src), fmt.Errorf("gofmt generated Go: %v", err)
	}
	return out, nil
}

func (s *Schema) goWrite(p func(string, ...any), t *Type, x string, ind int) {
	tab := strings.Repeat("\t", ind)
	switch t.Kind {
	case Prim:
		m := map[string]string{"uint": "uvarint", "int": "varint", "bool": "bool", "bytes": "bytes", "str": "str"}[t.Name]
		p("%sw.%s(%s)\n", tab, m, x)
	case Ref, EnumT:
		p("%sw.uvarint(uint64(%s))\n", tab, x)
	case OptRef:
		p("%sw.optRef(%s)\n", tab, x)
	case RecordT:
		p("%sw.write%s(&%s)\n", tab, t.Name, x)
	case OptRecord:
		p("%sif %s == nil {\n%s\tw.bool(false)\n%s} else {\n%s\tw.bool(true)\n%s\tw.write%s(%s)\n%s}\n", tab, x, tab, tab, tab, tab, t.Name, x, tab)
	case UnionT:
		p("%sw.write%s(%s)\n", tab, t.Name, x)
	case OptUnion:
		p("%sw.writeOpt%s(%s)\n", tab, t.Name, x)
	case List:
		iv := fmt.Sprintf("i%d", ind)
		p("%sw.uvarint(uint64(len(%s)))\n%sfor %s := range %s {\n", tab, x, tab, iv, x)
		s.goWrite(p, t.Elem, x+"["+iv+"]", ind+1)
		p("%s}\n", tab)
	}
}

func (s *Schema) goRead(p func(string, ...any), t *Type, x string, ind, depth int) {
	tab := strings.Repeat("\t", ind)
	switch t.Kind {
	case Prim:
		m := map[string]string{"uint": "uvarint", "int": "varint", "bool": "bool", "bytes": "bytes", "str": "str"}[t.Name]
		p("%s%s = r.%s()\n", tab, x, m)
	case Ref:
		switch t.Name {
		case "type":
			p("%s%s = r.typeRef()\n", tab, x)
		case "pos":
			p("%s%s = r.posRef()\n", tab, x)
		case "local":
			p("%s%s = r.localRef()\n", tab, x)
		case "label":
			p("%s%s = r.labelRef()\n", tab, x)
		default:
			p("%s%s = r.ref(ref%s)\n", tab, x, exported(t.Name))
		}
	case OptRef:
		switch t.Name {
		case "local":
			p("%s%s = r.optLocalRef()\n", tab, x)
		case "label":
			p("%s%s = r.optLabelRef()\n", tab, x)
		default:
			p("%s%s = r.optRef(ref%s)\n", tab, x, exported(t.Name))
		}
	case EnumT:
		p("%s%s = %s(r.uvarint())\n%sif !%s.Valid() {\n%s\tr.failf(\"bad %s %%d\", %s)\n%s}\n", tab, x, t.Name, tab, x, tab, t.Name, x, tab)
	case RecordT:
		p("%sr.read%s(&%s)\n", tab, t.Name, x)
	case OptRecord:
		p("%sif r.bool() {\n%s\t%s = new(%s)\n%s\tr.read%s(%s)\n%s}\n", tab, tab, x, t.Name, tab, t.Name, x, tab)
	case UnionT:
		p("%s%s = r.read%s()\n", tab, x, t.Name)
	case OptUnion:
		p("%s%s = r.readOpt%s()\n", tab, x, t.Name)
	case List:
		iv := fmt.Sprintf("i%d", ind)
		p("%s%s = make(%s, r.count())\n%sfor %s := range %s {\n", tab, x, s.goType(t), tab, iv, x)
		s.goRead(p, t.Elem, x+"["+iv+"]", ind+1, depth+1)
		p("%s}\n", tab)
	}
}
