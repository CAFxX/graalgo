var javaReserved = map[string]bool{}

func init() {
	for _, w := range strings.Fields(`abstract assert boolean break byte case catch char class const continue
		default do double else enum extends final finally float for goto if implements import instanceof
		int interface long native new package private protected public return short static strictfp super
		switch synchronized this throw throws transient try void volatile while true false null var yield
		record sealed permits hashCode toString equals getClass`) {
		javaReserved[w] = true
	}
}

func javaField(name string) string {
	if javaReserved[name] {
		return name + "_"
	}
	return name
}

func (s *Schema) javaType(t *Type) string {
	switch t.Kind {
	case Prim:
		return map[string]string{"uint": "long", "int": "long", "bool": "boolean", "bytes": "byte[]", "str": "int"}[t.Name]
	case Ref, OptRef, EnumT:
		return "int"
	case RecordT, OptRecord, UnionT, OptUnion:
		return "Gir." + t.Name
	case List:
		return s.javaType(t.Elem) + "[]"
	}
	panic("unreachable")
}

// javaElemNew returns "new T[n]" for an array of t's element type, which
// for nested arrays must put the length first: new long[n][].
func (s *Schema) javaNewArray(elem *Type, n string) string {
	base := s.javaType(elem)
	if i := strings.Index(base, "["); i >= 0 {
		return "new " + base[:i] + "[" + n + "]" + base[i:]
	}
	return "new " + base + "[" + n + "]"
}

const javaHeader = "// Code generated by internal/toolexec/ir/gen from internal/toolexec/ir/schema.txt; DO NOT EDIT.\n\npackage graalgo.gir;\n\n"

// GenerateJavaNodes returns Gir.java: constants, enums, records, unions.
func (s *Schema) GenerateJavaNodes() []byte {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p(javaHeader)
	p("/** The GIR node and record types (docs/arch/toolexec-design.md §3.2). String fields hold\n")
	p(" * STRINGS indices, type fields 1-based TYPES ids (0 = none), optional references -1 for none. */\n")
	p("public final class Gir {\n    private Gir() {}\n\n")
	p("    public static final int SCHEMA_VERSION = %d;\n", s.Version)
	p("    /** Maximum node nesting (schema.txt maxdepth). */\n    public static final int MAX_DEPTH = %d;\n", s.MaxDepth)
	p("    public static final byte[] SCHEMA_HASH = {")
	for i, c := range s.Hash {
		if i > 0 {
			p(", ")
		}
		p("(byte) 0x%02x", c)
	}
	p("};\n\n")
	for _, e := range s.Enums {
		p("    public static final class %s {\n        private %s() {}\n", e.Name, e.Name)
		for _, v := range e.Values {
			if v.Comment != "" {
				p("        /** %s */\n", v.Comment)
			}
			p("        public static final int %s = %d;\n", upperSnake(v.Name), v.Value)
		}
		p("\n        public static boolean valid(long v) {\n            return ")
		for i, v := range e.Values {
			if i > 0 {
				p(" || ")
			}
			p("v == %d", v.Value)
		}
		p(";\n        }\n\n        public static String name(int v) {\n            return switch (v) {\n")
		for _, v := range e.Values {
			p("                case %d -> \"%s\";\n", v.Value, v.Name)
		}
		p("                default -> \"%s(\" + v + \")\";\n            };\n        }\n    }\n\n", e.Name)
	}
	params := func(fields []*Field) string {
		var parts []string
		for _, f := range fields {
			parts = append(parts, s.javaType(f.Type)+" "+javaField(f.Name))
		}
		return strings.Join(parts, ", ")
	}
	for _, r := range s.Records {
		p("    public record %s(%s) {\n    }\n\n", r.Name, params(r.Fields))
	}
	for _, u := range s.Unions {
		p("    public sealed interface %s permits ", u.Name)
		for i, m := range u.Members {
			if i > 0 {
				p(", ")
			}
			p("%s.%s", u.Name, m.Name)
		}
		p(" {\n        /** The member's kind number on the wire. */\n        int unionTag();\n\n")
		for _, m := range u.Members {
			p("        record %s(%s) implements %s {\n            @Override\n            public int unionTag() {\n                return %d;\n            }\n        }\n\n", m.Name, params(m.Fields), u.Name, m.Kind)
		}
		p("    }\n\n")
	}
	p("    /** The typed (non-raw) sections of a GIR file. */\n    public static final class Sections {\n")
	for _, sec := range s.Sections {
		if !sec.Raw {
			p("        public %s %s;\n", s.javaType(sec.Type), javaField(sec.Field))
		}
	}
	p("    }\n}\n")
	return []byte(b.String())
}

// GenerateJavaCodec returns GirCodec.java.
func (s *Schema) GenerateJavaCodec() []byte {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p(javaHeader)
	p("/** Generated readers and writers for every GIR record and union. */\nfinal class GirCodec {\n    private GirCodec() {}\n\n")
	for _, sec := range s.Sections {
		p("    static final int SEC_%s = %d;\n", sec.Name, sec.ID)
	}
	p("\n    static final int[] SECTION_IDS = {")
	for i, sec := range s.Sections {
		if i > 0 {
			p(", ")
		}
		p("SEC_%s", sec.Name)
	}
	p("};\n\n    static String sectionName(int id) {\n        return switch (id) {\n")
	for _, sec := range s.Sections {
		p("            case %d -> \"%s\";\n", sec.ID, sec.Name)
	}
	p("            default -> \"section \" + id;\n        };\n    }\n\n")
	p("    /** Section indexed by each reference kind (GirReader.REF_*). */\n    static final int[] REF_SECTIONS = {")
	for i, k := range []string{"type", "sym", "obj", "fn"} {
		if i > 0 {
			p(", ")
		}
		p("SEC_%s", RefSections[k])
	}
	p("};\n\n")

	p("    static void readTypedSection(GirReader r, Gir.Sections s, int id) {\n        switch (id) {\n")
	for _, sec := range s.Sections {
		if sec.Raw {
			continue
		}
		p("            case SEC_%s -> {\n", sec.Name)
		s.javaRead(p, sec.Type, "v", 4)
		p("                s.%s = v;\n            }\n", javaField(sec.Field))
	}
	p("            default -> throw new IllegalArgumentException(\"not a typed section: \" + id);\n        }\n    }\n\n")
	p("    static void writeTypedSection(GirWriter w, Gir.Sections s, int id) {\n        switch (id) {\n")
	for _, sec := range s.Sections {
		if sec.Raw {
			continue
		}
		p("            case SEC_%s -> {\n", sec.Name)
		s.javaWrite(p, sec.Type, "s."+javaField(sec.Field), 4)
		p("            }\n")
	}
	p("            default -> throw new IllegalArgumentException(\"not a typed section: \" + id);\n        }\n    }\n\n")

	for _, r := range s.Records {
		p("    static Gir.%s read%s(GirReader r) {\n", r.Name, r.Name)
		ind := 2
		if r.Scope {
			p("        r.pushScope();\n        try {\n")
			ind = 3
		}
		var names []string
		for _, f := range r.Fields {
			n := "f_" + f.Name
			names = append(names, n)
			s.javaRead(p, f.Type, n, ind)
			if r.Scope {
				switch f.Name {
				case "positions":
					p("%sr.scopeSetPositions(%s.length);\n", strings.Repeat("    ", ind), n)
				case "locals":
					p("%sr.scopeSetLocals(%s.length);\n", strings.Repeat("    ", ind), n)
				case "labels":
					p("%sr.scopeSetLabels(%s.length);\n", strings.Repeat("    ", ind), n)
				}
			}
		}
		p("%sreturn new Gir.%s(%s);\n", strings.Repeat("    ", ind), r.Name, strings.Join(names, ", "))
		if r.Scope {
			p("        } finally {\n            r.popScope();\n        }\n")
		}
		p("    }\n\n")
		p("    static void write%s(GirWriter w, Gir.%s v) {\n", r.Name, r.Name)
		for _, f := range r.Fields {
			s.javaWrite(p, f.Type, "v."+javaField(f.Name)+"()", 2)
		}
		p("    }\n\n")
	}
	for _, u := range s.Unions {
		p("    static Gir.%s read%s(GirReader r) {\n        return read%sKind(r, r.uvarint());\n    }\n\n", u.Name, u.Name, u.Name)
		p("    static Gir.%s readOpt%s(GirReader r) {\n        long k = r.uvarint();\n        return k == 0 ? null : read%sKind(r, k);\n    }\n\n", u.Name, u.Name, u.Name)
		p("    private static Gir.%s read%sKind(GirReader r, long k) {\n        r.enter();\n        try {\n", u.Name, u.Name)
		p("            if (k == 0 || k > Integer.MAX_VALUE) {\n                throw r.fail(\"bad %s kind \" + Long.toUnsignedString(k));\n            }\n", u.Name)
		p("            switch ((int) k) {\n")
		for _, m := range u.Members {
			p("                case %d: {\n", m.Kind)
			var names []string
			for _, f := range m.Fields {
				n := "f_" + f.Name
				names = append(names, n)
				s.javaRead(p, f.Type, n, 5)
			}
			p("                    return new Gir.%s.%s(%s);\n                }\n", u.Name, m.Name, strings.Join(names, ", "))
		}
		p("                default:\n                    throw r.fail(\"bad %s kind \" + k);\n            }\n", u.Name)
		p("        } finally {\n            r.leave();\n        }\n    }\n\n")
		p("    static void write%s(GirWriter w, Gir.%s x) {\n        switch (x) {\n", u.Name, u.Name)
		for _, m := range u.Members {
			p("            case Gir.%s.%s v -> {\n                w.uvarint(%d);\n", u.Name, m.Name, m.Kind)
			for _, f := range m.Fields {
				s.javaWrite(p, f.Type, "v."+javaField(f.Name)+"()", 4)
			}
			p("            }\n")
		}
		p("        }\n    }\n\n")
		p("    static void writeOpt%s(GirWriter w, Gir.%s x) {\n        if (x == null) {\n            w.uvarint(0);\n        } else {\n            write%s(w, x);\n        }\n    }\n\n", u.Name, u.Name, u.Name)
	}
	p("}\n")
	return []byte(b.String())
}

var javaLoopVar = 0

func (s *Schema) javaRead(p func(string, ...any), t *Type, v string, ind int) {
	tab := strings.Repeat("    ", ind)
	switch t.Kind {
	case List:
		n := v + "_n"
		iv := v + "_i"
		p("%sint %s = r.count();\n%s%s %s = %s;\n", tab, n, tab, s.javaType(t), v, s.javaNewArray(t.Elem, n))
		p("%sfor (int %s = 0; %s < %s; %s++) {\n", tab, iv, iv, n, iv)
		ev := v + "_e"
		s.javaRead(p, t.Elem, ev, ind+1)
		p("%s    %s[%s] = %s;\n%s}\n", tab, v, iv, ev, tab)
	case EnumT:
		p("%slong %s_raw = r.uvarint();\n%sif (!Gir.%s.valid(%s_raw)) {\n%s    throw r.fail(\"bad %s \" + Long.toUnsignedString(%s_raw));\n%s}\n%sint %s = (int) %s_raw;\n",
			tab, v, tab, t.Name, v, tab, t.Name, v, tab, tab, v, v)
	default:
		p("%s%s %s = %s;\n", tab, s.javaType(t), v, s.javaReadExpr(t))
	}
}

func (s *Schema) javaReadExpr(t *Type) string {
	switch t.Kind {
	case Prim:
		return map[string]string{"uint": "r.uvarint()", "int": "r.varint()", "bool": "r.bool()", "bytes": "r.bytes()", "str": "r.str()"}[t.Name]
	case Ref:
		switch t.Name {
		case "type":
			return "r.typeRef()"
		case "pos":
			return "r.posRef()"
		case "local":
			return "r.localRef()"
		case "label":
			return "r.labelRef()"
		}
		return "r.ref(GirReader.REF_" + strings.ToUpper(t.Name) + ")"
	case OptRef:
		switch t.Name {
		case "local":
			return "r.optLocalRef()"
		case "label":
			return "r.optLabelRef()"
		}
		return "r.optRef(GirReader.REF_" + strings.ToUpper(t.Name) + ")"
	case RecordT:
		return "read" + t.Name + "(r)"
	case OptRecord:
		return "r.bool() ? read" + t.Name + "(r) : null"
	case UnionT:
		return "read" + t.Name + "(r)"
	case OptUnion:
		return "readOpt" + t.Name + "(r)"
	}
	panic("unreachable")
}

func (s *Schema) javaWrite(p func(string, ...any), t *Type, x string, ind int) {
	tab := strings.Repeat("    ", ind)
	switch t.Kind {
	case Prim:
		m := map[string]string{"uint": "uvarint", "int": "varint", "bool": "bool", "bytes": "bytes", "str": "uvarint"}[t.Name]
		p("%sw.%s(%s);\n", tab, m, x)
	case Ref, EnumT:
		p("%sw.uvarint(%s);\n", tab, x)
	case OptRef:
		p("%sw.optRef(%s);\n", tab, x)
	case RecordT:
		p("%swrite%s(w, %s);\n", tab, t.Name, x)
	case OptRecord:
		p("%sw.bool(%s != null);\n%sif (%s != null) {\n%s    write%s(w, %s);\n%s}\n", tab, x, tab, x, tab, t.Name, x, tab)
	case UnionT:
		p("%swrite%s(w, %s);\n", tab, t.Name, x)
	case OptUnion:
		p("%swriteOpt%s(w, %s);\n", tab, t.Name, x)
	case List:
		javaLoopVar++
		e := fmt.Sprintf("e%d", javaLoopVar)
		p("%sw.uvarint(%s.length);\n%sfor (%s %s : %s) {\n", tab, x, tab, s.javaType(t.Elem), e, x)
		s.javaWrite(p, t.Elem, e, ind+1)
		p("%s}\n", tab)
	}
}

// localsReach reports, per record and union name, whether a value of it can
// hold a `local` reference outside a nested scope record.
func (s *Schema) localsReach() map[string]bool {
	reach := map[string]bool{}
	var typeReaches func(t *Type) bool
	typeReaches = func(t *Type) bool {
		switch t.Kind {
		case Ref, OptRef:
			return t.Name == "local"
		case RecordT, OptRecord:
			if r := s.Record(t.Name); r != nil && r.Scope {
				return false
			}
			return reach[t.Name]
		case UnionT, OptUnion:
			return reach[t.Name]
		case List:
			return typeReaches(t.Elem)
		}
		return false
	}
	fieldsReach := func(fs []*Field) bool {
		for _, f := range fs {
			if typeReaches(f.Type) {
				return true
			}
		}
		return false
	}
	for changed := true; changed; {
		changed = false
		for _, r := range s.Records {
			if !reach[r.Name] && !r.Scope && fieldsReach(r.Fields) {
				reach[r.Name], changed = true, true
			}
		}
		for _, u := range s.Unions {
			if reach[u.Name] {
				continue
			}
			for _, m := range u.Members {
				if fieldsReach(m.Fields) {
					reach[u.Name], changed = true, true
					break
				}
			}
		}
	}
	return reach
}

// GenerateJavaLocals returns GirLocals.java: for every record and union that
// can hold a `local` reference, a visitor reporting each such reference
// (Expr.Local, declarations, captures, ...) in a subtree. A scope record
// (a function literal's body) is not entered: its locals index another
// table; the literal's captures are the enclosing scope's references.
// Generated, so a schema change cannot leave a reference kind unvisited.
func (s *Schema) GenerateJavaLocals() []byte {
	reach := s.localsReach()
	var b strings.Builder
	out := &b
	p := func(format string, a ...any) { fmt.Fprintf(out, format, a...) }
	// capture runs emit with output redirected and returns what it wrote.
	capture := func(emit func()) string {
		var tmp strings.Builder
		saved := out
		out = &tmp
		emit()
		out = saved
		return tmp.String()
	}
	p(javaHeader)
	p("import java.util.function.IntConsumer;\n\n")
	p("/** Every {@code local} reference in a GIR subtree, nested scopes excluded (schema.txt). */\n")
	p("public final class GirLocals {\n    private GirLocals() {}\n")
	var field func(t *Type, x string, ind int)
	field = func(t *Type, x string, ind int) {
		tab := strings.Repeat("    ", ind)
		switch t.Kind {
		case Ref:
			if t.Name == "local" {
				p("%sf.accept(%s);\n", tab, x)
			}
		case OptRef:
			if t.Name == "local" {
				p("%sif (%s >= 0) {\n%s    f.accept(%s);\n%s}\n", tab, x, tab, x, tab)
			}
		case RecordT, UnionT:
			if reach[t.Name] {
				p("%svisit(%s, f);\n", tab, x)
			}
		case OptRecord, OptUnion:
			if reach[t.Name] {
				p("%sif (%s != null) {\n%s    visit(%s, f);\n%s}\n", tab, x, tab, x, tab)
			}
		case List:
			javaLoopVar++
			v := fmt.Sprintf("e%d", javaLoopVar)
			inner := capture(func() { field(t.Elem, v, ind+1) })
			if inner != "" {
				p("%sfor (%s %s : %s) {\n%s%s}\n", tab, s.javaType(t.Elem), v, x, inner, tab)
			}
		}
	}
	for _, r := range s.Records {
		if !reach[r.Name] {
			continue
		}
		p("\n    public static void visit(Gir.%s x, IntConsumer f) {\n", r.Name)
		for _, fl := range r.Fields {
			field(fl.Type, "x."+javaField(fl.Name)+"()", 2)
		}
		p("    }\n")
	}
	for _, u := range s.Unions {
		if !reach[u.Name] {
			continue
		}
		p("\n    public static void visit(Gir.%s x, IntConsumer f) {\n        switch (x) {\n", u.Name)
		for _, m := range u.Members {
			body := capture(func() {
				for _, fl := range m.Fields {
					field(fl.Type, "m."+javaField(fl.Name)+"()", 4)
				}
			})
			p("            case Gir.%s.%s m -> {\n%s            }\n", u.Name, m.Name, body)
		}
		p("        }\n    }\n")
	}
	p("}\n")
	return []byte(b.String())
}

// Outputs returns every generated file, keyed by its path relative to the
// ir directory.
func Outputs(irDir string) (map[string][]byte, error) {
	src, err := os.ReadFile(filepath.Join(irDir, "schema.txt"))
	if err != nil {
		return nil, err
	}
	s, err := Parse(src)
	if err != nil {
		return nil, err
	}
	goSrc, err := s.GenerateGo()
	if err != nil {
		return nil, err
	}
	javaLoopVar = 0
	javaDir := filepath.Join("..", "..", "backend", "gir", "src", "main", "java", "graalgo", "gir")
	return map[string][]byte{
		"gir_gen.go":                             goSrc,
		filepath.Join(javaDir, "Gir.java"):       s.GenerateJavaNodes(),
		filepath.Join(javaDir, "GirCodec.java"):  s.GenerateJavaCodec(),
		filepath.Join(javaDir, "GirLocals.java"): s.GenerateJavaLocals(),
	}, nil
}

// WriteAll regenerates every output under irDir.
func WriteAll(irDir string) error {
	outs, err := Outputs(irDir)
	if err != nil {
		return err
	}
	for rel, data := range outs {
		p := filepath.Join(irDir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}
