package intrinsics

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// JavaPath is the generated dispatch table, relative to internal/toolexec.
const JavaPath = "../backend/truffle/src/main/java/graalgo/go/intrinsics/IntrinsicTable.java"

// javaType is the carrier of a Go type in the node package's calling
// convention (truffle-design §15): every integer type a long in canonical
// extended form, both float types a double, bool a boolean, string a Str,
// everything else a reference.
func javaType(key string) string {
	switch key {
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr":
		return "long"
	case "float32", "float64":
		return "double"
	case "bool":
		return "boolean"
	case "string":
		return "Str"
	}
	return "Object"
}

// Java returns the source of IntrinsicTable.java for t.
func (t *Table) Java() string {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p("// Code generated by `go generate ./intrinsics` (internal/toolexec) from registry.txt. DO NOT EDIT.\n")
	p("package graalgo.go.intrinsics;\n\n")
	p("import com.oracle.truffle.api.frame.VirtualFrame;\n")
	p("import com.oracle.truffle.api.nodes.RootNode;\n")
	p("import graalgo.go.values.Str;\n")
	p("import graalgo.language.GoLanguage;\n\n")
	p("/**\n")
	p(" * The intrinsic registry's dispatch table (toolexec-design D9, §5.3; GG-0020): one root\n")
	p(" * node per registered Go symbol, calling the static method that implements it with the Go\n")
	p(" * arguments unboxed from the calling convention ({@code arguments[0]} is the unused\n")
	p(" * environment). The linker resolves functions against the same registry, and a bundle\n")
	p(" * records its {@link #VERSION} and {@link #HASH}.\n")
	p(" */\n")
	p("public final class IntrinsicTable {\n")
	p("    private IntrinsicTable() {}\n\n")
	p("    public static final int VERSION = %d;\n", t.Version)
	p("    public static final String HASH = \"%x\";\n\n", t.Hash[:])
	p("    /** The root node implementing {@code symbol}, or null if it is not registered. */\n")
	p("    public static RootNode root(GoLanguage language, String symbol) {\n")
	p("        switch (symbol) {\n")
	for _, e := range t.Entries {
		p("            case %q:\n                return new R_%s(language);\n", e.Symbol, MethodName(e.Symbol))
	}
	p("            default:\n                return null;\n")
	p("        }\n    }\n\n")
	p("    abstract static class Root extends RootNode {\n")
	p("        private final String name;\n\n")
	p("        Root(GoLanguage language, String name) {\n            super(language);\n            this.name = name;\n        }\n\n")
	p("        @Override\n        public String getName() {\n            return name;\n        }\n\n")
	p("        @Override\n        public boolean isInternal() {\n            return true;\n        }\n    }\n")
	for _, e := range t.Entries {
		params, results, _ := SplitSig(e.Sig)
		m := MethodName(e.Symbol)
		var args []string
		args = append(args, "this")
		// A method's receiver travels as the first Go argument; the signature
		// (the method's type key) does not list it.
		first := 1
		if e.Method {
			args = append(args, "a[1]")
			first = 2
		}
		for i, pt := range params {
			jt := javaType(pt)
			if jt == "Object" {
				args = append(args, fmt.Sprintf("a[%d]", i+first))
			} else {
				args = append(args, fmt.Sprintf("(%s) a[%d]", jt, i+first))
			}
		}
		call := fmt.Sprintf("%s.%s(%s)", e.Class, m, strings.Join(args, ", "))
		p("\n    /** {@code %s}: {@code %s}. */\n", e.Symbol, e.Sig)
		p("    static final class R_%s extends Root {\n", m)
		p("        R_%s(GoLanguage language) {\n            super(language, %q);\n        }\n\n", m, e.Symbol)
		p("        @Override\n        public Object execute(VirtualFrame frame) {\n")
		if len(params) > 0 || e.Method {
			p("            Object[] a = frame.getArguments();\n")
		}
		if len(results) == 0 {
			p("            %s;\n            return null;\n", call)
		} else {
			p("            return %s;\n", call)
		}
		p("        }\n    }\n")
	}
	p("}\n")
	out := b.String()
	if !strings.Contains(out, "(Str) ") {
		out = strings.Replace(out, "import graalgo.go.values.Str;\n", "", 1)
	}
	return out
}

// WriteJava writes the generated Java file; dir is internal/toolexec.
func (t *Table) WriteJava(dir string) error {
	path := filepath.Join(dir, filepath.FromSlash(JavaPath))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(t.Java()), 0o644)
}
