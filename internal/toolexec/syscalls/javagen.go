package syscalls

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// JavaPath is the generated Java table, relative to internal/toolexec.
const JavaPath = "../backend/truffle/src/main/java/graalgo/syscall/SyscallTable.java"

// Java returns the source of SyscallTable.java for t.
func (t *Table) Java() string {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p("// Code generated by `go generate ./syscalls` (internal/toolexec) from table.txt. DO NOT EDIT.\n")
	p("package graalgo.syscall;\n\n")
	p("/**\n")
	p(" * The syscall role table (internal/toolexec/syscalls/table.txt; toolexec-design §5.6, W8a):\n")
	p(" * per linux/amd64 number, whether the call may block and the role of each argument word.\n")
	p(" * Checked against the standard library's call sites by {@code go test ./syscalls}.\n")
	p(" */\n")
	p("final class SyscallTable {\n")
	p("    private SyscallTable() {}\n\n")
	maxNr := 0
	for _, e := range t.Entries {
		if e.Nr > maxNr {
			maxNr = e.Nr
		}
	}
	p("    private static final Entry[] BY_NR = new Entry[%d];\n\n", maxNr+1)
	p("    static {\n")
	for _, e := range t.Entries {
		var roles []string
		for _, r := range e.Roles {
			switch r.Kind {
			case Val:
				roles = append(roles, "Role.VAL")
			case CStr:
				roles = append(roles, "Role.CSTR")
			case Bytes:
				roles = append(roles, fmt.Sprintf("Role.bytes(%d, %t, %t)", r.LenArg, r.Dir == Out, r.FilledResult))
			}
		}
		p("        BY_NR[%d] = new Entry(%d, %q, %t, new Role[] {%s});\n", e.Nr, e.Nr, e.Name, e.MayBlock, strings.Join(roles, ", "))
	}
	p("    }\n\n")
	p("    /** The entry of system call {@code nr}, or null if the table has none. */\n")
	p("    static Entry get(long nr) {\n")
	p("        return nr >= 0 && nr < BY_NR.length ? BY_NR[(int) nr] : null;\n")
	p("    }\n")
	p("}\n")
	return b.String()
}

// WriteJava writes the generated Java file; dir is internal/toolexec.
func (t *Table) WriteJava(dir string) error {
	path := filepath.Join(dir, filepath.FromSlash(JavaPath))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(t.Java()), 0o644)
}

func readJava(dir string) (string, error) {
	b, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(JavaPath)))
	return string(b), err
}
