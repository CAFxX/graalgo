    public static final class DivC extends Ref {
        @Child private Expr l;
        @Child private Expr r;
        private final boolean single;

        public DivC(Expr l, Expr r, boolean single) {
            this.l = l;
            this.r = r;
            this.single = single;
        }

        @Override
        public Object executeGeneric(VirtualFrame frame) {
            Complex a = (Complex) l.executeGeneric(frame);
            Complex b = (Complex) r.executeGeneric(frame);
            Complex q = div(a, b);
            return single ? new Complex((float) q.re(), (float) q.im()) : q;
        }

        /** runtime.complex128div. */
        private static Complex div(Complex n, Complex m) {
            double e;
            double f;
            if (Math.abs(m.re()) >= Math.abs(m.im())) {
                double ratio = m.im() / m.re();
                double denom = m.re() + ratio * m.im();
                e = (n.re() + n.im() * ratio) / denom;
                f = (n.im() - n.re() * ratio) / denom;
            } else {
                double ratio = m.re() / m.im();
                double denom = m.im() + ratio * m.re();
                e = (n.re() * ratio + n.im()) / denom;
                f = (n.im() * ratio - n.re()) / denom;
            }
            if (Double.isNaN(e) && Double.isNaN(f)) {
                double a = n.re();
                double b = n.im();
                double c = m.re();
                double d = m.im();
                if (c == 0 && d == 0 && (!Double.isNaN(a) || !Double.isNaN(b))) {
                    e = Math.copySign(Double.POSITIVE_INFINITY, c) * a;
                    f = Math.copySign(Double.POSITIVE_INFINITY, c) * b;
                } else if ((Double.isInfinite(a) || Double.isInfinite(b)) && !Double.isInfinite(c)
                        && !Double.isInfinite(d) && !Double.isNaN(c) && !Double.isNaN(d)) {
                    a = Math.copySign(Double.isInfinite(a) ? 1 : 0, a);
                    b = Math.copySign(Double.isInfinite(b) ? 1 : 0, b);
                    e = Double.POSITIVE_INFINITY * (a * c + b * d);
                    f = Double.POSITIVE_INFINITY * (b * c - a * d);
                } else if ((Double.isInfinite(c) || Double.isInfinite(d)) && !Double.isInfinite(a)
                        && !Double.isInfinite(b) && !Double.isNaN(a) && !Double.isNaN(b)) {
                    c = Math.copySign(Double.isInfinite(c) ? 1 : 0, c);
                    d = Math.copySign(Double.isInfinite(d) ? 1 : 0, d);
                    e = 0 * (a * c + b * d);
                    f = 0 * (b * c - a * d);
                }
            }
            return new Complex(e, f);
        }
    }

    public static final class NegC extends Ref {
        @Child private Expr x;

        public NegC(Expr x) {
            this.x = x;
        }

        @Override
        public Object executeGeneric(VirtualFrame frame) {
            Complex c = (Complex) x.executeGeneric(frame);
            return new Complex(-c.re(), -c.im());
        }
    }

    public static final class MakeComplex extends Ref {
        @Child private F64 re;
        @Child private F64 im;

        public MakeComplex(F64 re, F64 im) {
            this.re = re;
            this.im = im;
        }

        @Override
        public Object executeGeneric(VirtualFrame frame) {
            double r = re.executeDouble(frame);
            return new Complex(r, im.executeDouble(frame));
        }
    }

