    /** float → int64, gc/amd64 semantics: NaN and out-of-range give the minimum value. */
    public static final class F64ToI64 extends I64 {
        @Child private F64 x;

        public F64ToI64(F64 x) {
            this.x = x;
        }

        @Override
        public long executeLong(VirtualFrame frame) {
            return toLong(x.executeDouble(frame));
        }

        static long toLong(double v) {
            return v >= -0x1p63 && v < 0x1p63 ? (long) v : Long.MIN_VALUE;
        }
    }

    /** float → int32 and narrower (the result is then wrapped): CVTTSD2SL semantics. */
    public static final class F64ToI32 extends I64 {
        @Child private F64 x;

        public F64ToI32(F64 x) {
            this.x = x;
        }

        @Override
        public long executeLong(VirtualFrame frame) {
            double v = x.executeDouble(frame);
            return v > -0x1p31 - 1 && v < 0x1p31 ? (int) v : Integer.MIN_VALUE;
        }
    }

    /** float → uint64, gc/amd64 semantics (go1.27: out of range and NaN give 1&lt;&lt;63). */
    public static final class F64ToU64 extends I64 {
        @Child private F64 x;

        public F64ToU64(F64 x) {
            this.x = x;
        }

        @Override
        public long executeLong(VirtualFrame frame) {
            double v = x.executeDouble(frame);
            if (v < 0x1p63) {
                return F64ToI64.toLong(v);
            } else if (v < 0x1p64) {
                return (long) (v - 0x1p63) ^ Long.MIN_VALUE;
            }
            return Long.MIN_VALUE;
        }
    }

