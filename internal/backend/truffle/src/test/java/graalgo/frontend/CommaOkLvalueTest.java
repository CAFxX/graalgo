package graalgo.frontend;

import com.oracle.truffle.api.source.Source;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Comma-ok assignment with non-identifier LHS targets.
 *
 * <p>Regression test: {@code w.err, _ = a[i].(error)} (selector LHS, blank,
 * type-assertion in comma-ok position — the shape at fmt/errors.go:49) was
 * rejected by the v1 backend with "comma-ok target must be a variable".
 * The exporter correctly emits general assignable LHS (ident, index,
 * selector, deref) for comma-ok forms; the backend now lowers them via the
 * same {@code writeLvalue} path as plain assignments.
 *
 * <p>Test resource {@code comma-ok-nonident-lhs.json} is the gofrontend wire
 * document for a program exercising selector, index, and deref comma-ok LHS
 * targets (plus an ident control). Generated by gofrontend; loaded from the
 * source tree like the other frontend test resources.
 */
public final class CommaOkLvalueTest {

    private static String loadResource(String name) throws Exception {
        return Files.readString(
                Path.of("src/test/resources/frontend", name),
                StandardCharsets.UTF_8);
    }

    /**
     * Positive: a program with selector/index/deref comma-ok LHS targets
     * builds without exception. Before the fix, buildProgram threw
     * FrontendException("comma-ok target must be a variable").
     */
    public void testCommaOkNonIdentLhsBuilds() throws Exception {
        String json = loadResource("comma-ok-nonident-lhs.json");
        Source source = Source.newBuilder("go", "package main", "commaok.go").build();
        // Must not throw: selector, index, and deref are all valid
        // comma-ok assignment targets in Go.
        new NodeFactory(source).buildProgram(json);
    }

    /**
     * Negative: an assign node whose LHS has an unknown kind is still
     * rejected fail-fast. Guards that the general-lvalue support did not
     * loosen LHS validation.
     */
    public void testCommaOkInvalidLhsKindRejected() throws Exception {
        String json = loadResource("comma-ok-nonident-lhs.json");
        // Corrupt the first LHS kind in the first assign node: the backend
        // must fail fast rather than silently accepting it.
        String bad = json.replaceFirst("\"kind\": \"selector\"", "\"kind\": \"frobnicate\"");
        if (bad.equals(json)) {
            throw new AssertionError("test resource has no selector LHS to corrupt");
        }
        Source source = Source.newBuilder("go", "package main", "commaok-bad.go").build();
        try {
            new NodeFactory(source).buildProgram(bad);
        } catch (FrontendException e) {
            if (!e.getMessage().contains("bad assignment lhs kind")) {
                throw new AssertionError(
                        "expected 'bad assignment lhs kind' in FrontendException, got <"
                                + e.getMessage() + ">");
            }
            return; // expected: clean fail-fast
        }
        throw new AssertionError("invalid LHS kind must fail fast with FrontendException");
    }
}
