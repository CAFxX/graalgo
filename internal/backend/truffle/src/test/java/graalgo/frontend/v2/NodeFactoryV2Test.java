    private static void check(boolean cond, String msg) {
        if (!cond) {
            throw new AssertionError(msg);
        }
    }

    private static byte[] hex(String s) {
        check(s.length() % 2 == 0, "odd hex length");
        byte[] out = new byte[s.length() / 2];
        for (int i = 0; i < out.length; i++) {
            out[i] = (byte) Integer.parseInt(s.substring(2 * i, 2 * i + 2), 16);
        }
        return out;
    }

    /**
     * F13-P1-1 (independent codebase review, 2026-11-09-13): a keyed
     * struct literal builds. Before the fix the v2 emitter's
     * {@code fieldname} keys fell through to {@code buildExpr}, which has
     * no {@code fieldname} case and threw
     * {@code FrontendException: unsupported expression kind "fieldname"} —
     * so no keyed struct literal could compile under v2.
     *
     * <p>A successful build proves the whole chain: the keys resolve to
     * field indices by name ({@code findFieldIndexByTypeId} throws on an
     * unknown field) and the values build as basic literals. It does not
     * execute the literal: {@code buildCompositeLit} passes a null struct
     * descriptor, so executing a v2 struct literal is a separate,
     * known gap (not this lane).
     */
    public void testKeyedStructLiteralBuilds() throws Exception {
        Source source = Source.newBuilder("go",
            "package main\ntype Point struct { X, Y int }\nfunc main() { p := Point{X: 1, Y: 2}; println(p.X, p.Y) }\n",
            "point.go").build();
        NodeFactoryV2.V2Program program =
            new NodeFactoryV2(source).buildProgram(hex(KEYED_STRUCT_LITERAL_HEX));
        check(program.functionCount() == 1,
            "function count = " + program.functionCount() + ", want 1");
        NodeFactoryV2.V2Function main = program.functions().get(0);
        check("main".equals(main.name()), "function name = " + main.name() + ", want main");
        check(main.hasBody(), "main must have a body");
        check(main.body() != null, "main body is null");
    }
