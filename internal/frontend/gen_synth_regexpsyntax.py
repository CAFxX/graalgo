#!/usr/bin/env python3
# P3-M9 (tier1c): generate synth_regexpsyntax.go (`regexp/syntax`) from gc
# 1.27.1's regexp/syntax.
#
# SCOPE-LIMITED: unicode tables (Scripts, Categories, etc.) are tier1a's
# (in progress). This generates the source importing unicode/unicode/utf8
# via the overlay; it will fail until tier1a lands. The corpus programs
# are .scopelimited with retest triggers.
import re, glob

GOROOT = "/home/hatch/tools/go/src/regexp/syntax"

HEADER = '''// P3-M9 (tier1c): synthetic `regexp/syntax` package.
//
// SCOPE-LIMITED: This package requires unicode tables (Scripts,
// Categories, SimpleFold, etc.) from tier1a's unicode package, which is
// in progress. The source is generated verbatim importing
// unicode/unicode/utf8 via the overlay; it will not type-check until
// tier1a lands.
//
// Retest trigger: unicode + unicode/utf8 land in the frontend overlay
// (tier1a).
//
// Generated by gen_synth_regexpsyntax.py from gc 1.27.1; DO NOT EDIT BY
// HAND (edit the generator and re-run).
package main

// syntheticRegexpSyntaxSource is the P3-M9 synthetic `regexp/syntax`
// package (scope-limited).
const syntheticRegexpSyntaxSource = `package syntax

'''

def main():
    parts = [HEADER]
    for path in sorted(glob.glob(f"{GOROOT}/*.go")):
        if "_test" in path:
            continue
        with open(path) as f:
            src = f.read()
        src = re.sub(r"^package syntax\n", "", src, count=1, flags=re.M)
        # Keep imports (unicode, etc.); strip backticks.
        src = src.replace("`", "'")
        # slices.Equal -> manual (slices is tier1a, but Equal is simple).
        parts.append(src.rstrip() + "\n\n")
    out = "".join(parts).rstrip() + "\n`\n"
    with open("/home/hatch/workspace/graalgo-m9/phases/phase1/frontend/synth_regexpsyntax.go", "w") as f:
        f.write(out)
    print("wrote synth_regexpsyntax.go", len(out), "bytes")

main()
