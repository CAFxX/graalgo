#!/usr/bin/env python3
# P3-M9 (tier1c): generate synth_regexpsyntax.go (`regexp/syntax`) from gc
# 1.27.1's regexp/syntax.
#
# The per-file sources are concatenated verbatim (each keeps its own
# import block); the frontend's synthetic-package builder merges those
# into one import block at load (hoistSyntheticImports in
# synth_machinery.go) — a general repair, not a generator concern.
#
# Backtick embedding: the concatenated source contains raw string
# literals (backticks), which cannot nest inside the outer backtick
# literal of the const declaration. The source is therefore emitted as
# backtick fragments joined around each inner backtick
# (`...` + "`" + `...`), never by replacing backticks with quotes
# (that turns raw strings like `i` into rune literals like 'i', which
# is lossy and unrecoverable). See restoreRawStrings in
# synth_machinery.go for the builder-side safety net covering the
# unambiguous (multi-char) residue of the old naive replacement.
import os
import re
import glob
import subprocess


def _graalgo_goroot():
    """Go installation whose gc 1.27.1 sources this generator reads
    (P1-R1-2: environment-driven so the generator is CI-runnable)."""
    g = os.environ.get("GRAALGO_GOROOT")
    if g:
        return g
    try:
        return subprocess.run(["go", "env", "GOROOT"], capture_output=True,
                              text=True, check=True).stdout.strip()
    except Exception as e:
        raise SystemExit(
            "gen_synth: cannot determine GOROOT; set GRAALGO_GOROOT (%s)" % e)

GOROOT = os.path.join(_graalgo_goroot(), "src", "regexp", "syntax")
OUT = os.path.join(os.environ.get("GEN_SYNTH_OUTDIR",
                               os.path.dirname(os.path.abspath(__file__))),
                   "synth_regexpsyntax.go")

HEADER = '''// SYNTHETIC (Principle 4) — regexp/syntax: vendored verbatim; the real GOROOT tree does not compile under graalgo (go:linkname / asm / intrinsics / unsafe in the source or its closure — B-4).
// RETIRES WHEN: graalgo compiles the real go1.27.1 GOROOT sources directly — then delete this file.
// RE-TEST TRIGGER: real-source compilation lands (B-4 phased removal: docs/arch/bridge-inventory.md).
// P3-M9 (tier1c): synthetic `regexp/syntax` package.
//
// Generated by gen_synth_regexpsyntax.py from gc 1.27.1; DO NOT EDIT BY
// HAND (edit the generator and re-run).
package main

// syntheticRegexpSyntaxSource is the P3-M9 synthetic `regexp/syntax`
// package: gc's sources concatenated verbatim, one import block per
// file (merged at load by the builder).
'''


def go_embed(s):
    """Render s as a Go string expression: backtick literals split at
    inner backticks (which cannot nest), joined with "`" fragments."""
    parts = s.split("`")
    if len(parts) == 1:
        return "`" + s + "`"
    out = ["`" + parts[0] + "`"]
    for p in parts[1:]:
        out.append('"`"')
        out.append("`" + p + "`")
    return "(" + " + ".join(out) + ")"


def main():
    chunks = ["package syntax\n\n"]
    for path in sorted(glob.glob(f"{GOROOT}/*.go")):
        if "_test" in path:
            continue
        with open(path) as f:
            src = f.read()
        src = re.sub(r"^package syntax\n", "", src, count=1, flags=re.M)
        chunks.append(src.rstrip() + "\n\n")
    inner = "".join(chunks).rstrip() + "\n"
    out = HEADER + \
        "const syntheticRegexpSyntaxSource = " + go_embed(inner) + "\n"
    with open(OUT, "w") as f:
        f.write(out)
    print("wrote", OUT, len(out), "bytes")


main()
