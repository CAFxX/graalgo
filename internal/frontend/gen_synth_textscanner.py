def strip_imports(src):
    src = re.sub(r'^import \(\n(?:.*\n)*?^\)\n', '', src, count=1, flags=re.M)
    src = re.sub(r'^import "[^"]*"\n', '', src, flags=re.M)
    return src

def strip_package(src):
    return re.sub(r"^package scanner\n", "", src, count=1, flags=re.M)

def main():
    with open(f"{GOROOT}/scanner.go") as f:
        src = f.read()
    src = strip_package(src)
    src = strip_imports(src)
    src = src.replace("utf8.DecodeRune", "__tsDecodeRune")
    src = src.replace("utf8.FullRune", "__tsFullRune")
    src = src.replace("utf8.RuneError", "__tsRuneError")
    src = src.replace("utf8.RuneSelf", "__tsRuneSelf")
    src = src.replace("utf8.UTFMax", "__tsUTFMax")
    src = src.replace("unicode.IsLetter", "__tsIsLetter")
    src = src.replace("unicode.IsDigit", "__tsIsDigit")
    # Handle backtick rune literal specially (can't have backtick in raw string).
    src = src.replace("'`'", "'\\x60'")
    # Strip remaining backticks (in comments).
    src = src.replace("`", "'")
    out = HEADER + src.rstrip() + "\n`\n"
    with open(os.path.join(OUTDIR, "synth_textscanner.go"), "w") as f:
        f.write(out)
    print("wrote synth_textscanner.go", len(out), "bytes")

main()
