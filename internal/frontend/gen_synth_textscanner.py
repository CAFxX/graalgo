#!/usr/bin/env python3
# P3-M9 (tier1c): generate synth_textscanner.go (`text/scanner`) from gc
# 1.27.1's text/scanner.
#
# Transformations (all documented in the emitted file header):
#  1. unicode/utf8 inlined as __ts* helpers (DecodeRune, FullRune,
#     RuneError, RuneSelf, UTFMax — algorithmic).
#  2. unicode.IsLetter/IsDigit used VERBATIM from the synthetic
#     `unicode` package (tier1a tables landed; the former ASCII-only
#     deviation was retired when those tables were verified complete
#     against gc's unicode sources — see R0-3 remediation).
#  3. scanner.go carried verbatim otherwise. No multi-result functions.
import os
import re
import subprocess

# --- P1-R1-2 portability prologue: GOROOT and OUTDIR are environment-driven
# so the generator is CI-runnable and never writes outside the repo.
#   GRAALGO_GOROOT   Go installation whose gc 1.27.1 sources are read
#                    (default: `go env GOROOT`).
#   GEN_SYNTH_OUTDIR directory for the generated file(s) (default: this
#                    script's directory, i.e. in-place regeneration).
_HERE = os.path.dirname(os.path.abspath(__file__))

def _graalgo_goroot():
    g = os.environ.get("GRAALGO_GOROOT")
    if g:
        return g
    try:
        return subprocess.run(["go", "env", "GOROOT"], capture_output=True,
                              text=True, check=True).stdout.strip()
    except Exception as e:
        raise SystemExit(
            "gen_synth: cannot determine GOROOT; set GRAALGO_GOROOT (%s)" % e)

OUTDIR = os.environ.get("GEN_SYNTH_OUTDIR", _HERE)

GOROOT = os.path.join(_graalgo_goroot(), "src", "text", "scanner")


HEADER = '''// P3-M9 (tier1c): synthetic `text/scanner` package.
//
// REAL Go source, embedded as text and type-checked on demand with the
// overlay importer (same mechanism as the P3-M7 synthetic math package,
// ADR-0007 D5).
//
// Value model:
//   - scanner.go is gc 1.27.1's implementation ported verbatim.
//   - DEVIATION 1 (documented): unicode/utf8 is not in the overlay
//     (tier1a). DecodeRune, FullRune, RuneError, RuneSelf, UTFMax are
//     inlined as __ts* helpers (algorithmic, no tables).
//   - DEVIATION 2 (RETIRED 2026-10-30, R0-3): unicode.IsLetter/IsDigit
//     were ASCII-only checks. The retest trigger has fired: the
//     synthetic `unicode` package now carries the full gc tables
//     (tables.go + letter.go + graphic.go + digit.go + casetables.go,
//     verified decl-complete against gc 1.27.1), so scanner.go's
//     unicode.IsLetter/IsDigit calls are now used verbatim via
//     `import "unicode"` (same synthetic-to-synthetic import mechanism
//     as slices -> cmp). Non-ASCII letters/digits are recognised.
//
// Generated by gen_synth_textscanner.py from gc 1.27.1; DO NOT EDIT BY
// HAND (edit the generator and re-run).
package main

// syntheticTextScannerSource is the P3-M9 synthetic `text/scanner` package.
const syntheticTextScannerSource = `package scanner

import "bytes"
import "fmt"
import "io"
import "os"
import "unicode"

// ---- Deviation 1: inlined utf8 ----
const __tsRuneError = '\\uFFFD'
const __tsRuneSelf = 0x80
const __tsUTFMax = 4

func __tsDecodeRune(p []byte) (r rune, size int) {
	if len(p) == 0 {
		return __tsRuneError, 0
	}
	c := p[0]
	if c < __tsRuneSelf {
		return rune(c), 1
	}
	if c < 0xC2 || c >= 0xF5 {
		return __tsRuneError, 1
	}
	if c < 0xE0 {
		if len(p) < 2 {
			return __tsRuneError, 1
		}
		return rune(c&0x1F)<<6 | rune(p[1]&0x3F), 2
	}
	if c < 0xF0 {
		if len(p) < 3 {
			return __tsRuneError, 1
		}
		return rune(c&0x0F)<<12 | rune(p[1]&0x3F)<<6 | rune(p[2]&0x3F), 3
	}
	if len(p) < 4 {
		return __tsRuneError, 1
	}
	return rune(c&0x07)<<18 | rune(p[1]&0x3F)<<12 | rune(p[2]&0x3F)<<6 | rune(p[3]&0x3F), 4
}

func __tsFullRune(p []byte) bool {
	if len(p) == 0 {
		return false
	}
	c := p[0]
	if c < __tsRuneSelf {
		return true
	}
	var n int
	switch {
	case c < 0xE0:
		n = 2
	case c < 0xF0:
		n = 3
	default:
		n = 4
	}
	return len(p) >= n
}

'''

def strip_imports(src):
    src = re.sub(r'^import \(\n(?:.*\n)*?^\)\n', '', src, count=1, flags=re.M)
    src = re.sub(r'^import "[^"]*"\n', '', src, flags=re.M)
    return src

def strip_package(src):
    return re.sub(r"^package scanner\n", "", src, count=1, flags=re.M)

def main():
    with open(f"{GOROOT}/scanner.go") as f:
        src = f.read()
    src = strip_package(src)
    src = strip_imports(src)
    src = src.replace("utf8.DecodeRune", "__tsDecodeRune")
    src = src.replace("utf8.FullRune", "__tsFullRune")
    src = src.replace("utf8.RuneError", "__tsRuneError")
    src = src.replace("utf8.RuneSelf", "__tsRuneSelf")
    src = src.replace("utf8.UTFMax", "__tsUTFMax")
    # unicode.IsLetter/IsDigit pass through verbatim (synthetic unicode).
    # Handle backtick rune literal specially (can't have backtick in raw string).
    src = src.replace("'`'", "'\\x60'")
    # Strip remaining backticks (in comments).
    src = src.replace("`", "'")
    out = HEADER + src.rstrip() + "\n`\n"
    with open(os.path.join(OUTDIR, "synth_textscanner.go"), "w") as f:
        f.write(out)
    print("wrote synth_textscanner.go", len(out), "bytes")

main()
