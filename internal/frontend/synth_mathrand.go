// P3-M9: __randReadPair defined here (used by readBuf and __randRead).
type __randReadPair struct {
	n   int
	err error
}

func (r *Rand) readBuf(p []byte, src Source) __randReadPair {
	var n int
	var err error
	pos := r.readPos
	val := r.readVal
	rng, _ := src.(*rngSource)
	for n = 0; n < len(p); n++ {
		if pos == 0 {
			if rng != nil {
				val = rng.Int63()
			} else {
				val = src.Int63()
			}
			pos = 7
		}
		p[n] = byte(val)
		val >>= 8
		pos--
	}
	r.readPos = pos
	r.readVal = val
	return __randReadPair{n: n, err: err}
}

