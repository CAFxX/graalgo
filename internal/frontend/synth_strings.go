// stringsDecodeLastRune decodes the last UTF-8 encoding in s, ported from
// utf8.DecodeLastRuneInString.
func stringsDecodeLastRune(s string) stringsRuneSize {
	end := len(s)
	if end == 0 {
		return stringsRuneSize{int64(stringsRuneError), 0}
	}
	start := end - 1
	r := rune(s[start])
	if r < stringsRuneSelf {
		return stringsRuneSize{int64(r), 1}
	}
	// Guard against O(n^2) behavior on long invalid runs.
	lim := end - stringsUTFMax
	if lim < 0 {
		lim = 0
	}
	for start--; start >= lim; start-- {
		// RuneStart: break on ASCII or a multi-byte lead byte (i.e. any
		// byte that is not a continuation byte 0x80-0xBF).
		if s[start] < stringsRuneSelf || s[start] >= 0xC0 {
			break
		}
	}
	if start < 0 {
		start = 0
	}
	dc1 := stringsDecodeRune(s[start:end])
	r, size := rune(dc1.r), dc1.size
	if start+size != end {
		return stringsRuneSize{int64(stringsRuneError), 1}
	}
	return stringsRuneSize{int64(r), size}
}

// stringsRuneLen reports the UTF-8 encoding length of r, ported from
// utf8.RuneLen.
func stringsRuneLen(r rune) int {
	switch {
	case r < 0:
		return -1
	case r <= 0x7F:
		return 1
	case r <= 0x7FF:
		return 2
	case 0xD800 <= r && r <= 0xDFFF:
		return -1
	case r <= 0xFFFF:
		return 3
	case r <= stringsMaxRune:
		return 4
	}
	return -1
}

// stringsRuneCount counts the runes in s, ported from
// utf8.RuneCountInString.
func stringsRuneCount(s string) int {
	n := 0
	for i := 0; i < len(s); {
		if s[i] < stringsRuneSelf {
			i++
		} else {
			dc2 := stringsDecodeRune(s[i:])
			_, size := dc2.r, dc2.size
			i += size
		}
		n++
	}
	return n
}

// stringsAppendRune appends the UTF-8 encoding of r to b, ported from
// utf8.AppendRune (out-of-range runes encode as RuneError).
