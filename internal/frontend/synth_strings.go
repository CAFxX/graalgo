	func (b *Builder) Reset() {
		b.addr = nil
		b.buf = nil
	}

	// grow copies b.buf to a larger buffer. (copy from a nil slice NPEs
	// in the v1 runtime, so the copy is guarded.)
	func (b *Builder) grow(n int) {
		buf := make([]byte, len(b.buf), 2*cap(b.buf)+n)
		if b.buf != nil {
			copy(buf, b.buf)
		}
		b.buf = buf
	}

