	// stringsUpperLower is unicode.UpperLower = MaxRune+1, the sentinel delta
	// for alternating upper/lower sequences.
	const stringsUpperLower = 0x110000

	// stringsCaseRangeIndex binary-searches the case table, returning the
	// entry index or -1. (Returning *stringsCaseRange would need & on a
	// slice index expression, which is WS D.)
	func stringsCaseRangeIndex(r rune) int {
		lo := 0
		hi := len(stringsCaseRanges)
		for lo < hi {
			m := int(uint(lo+hi) >> 1)
			cr := stringsCaseRanges[m]
			if rune(cr.lo) <= r && r <= rune(cr.hi) {
				return m
			}
			if r < rune(cr.lo) {
				hi = m
			} else {
				lo = m + 1
			}
		}
		return -1
	}

	func stringsConvertCase(_case int, r rune, cr stringsCaseRange) rune {
		delta := cr.delta[_case] // int64
		if delta > stringsMaxRune {
			return rune(cr.lo) + ((r-rune(cr.lo))&^1 | rune(_case&1))
		}
		return r + rune(delta)
	}

