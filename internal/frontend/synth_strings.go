	// expanded to explicit [lo, hi] pairs.
	var stringsWhiteSpaceRanges = [][2]uint32{
		{0x0009, 0x000D},
		{0x0020, 0x0020},
		{0x0085, 0x0085},
		{0x00A0, 0x00A0},
		{0x1680, 0x1680},
		{0x2000, 0x200A},
		{0x2028, 0x2029},
		{0x202F, 0x202F},
		{0x205F, 0x205F},
		{0x3000, 0x3000},
	}

	func stringsIsSpace(r rune) bool {
		if r < stringsRuneSelf {
			return stringsASCIISpace[byte(r)] != 0
		}
		ur := uint32(r)
		for _, p := range stringsWhiteSpaceRanges {
			if p[0] <= ur && ur <= p[1] {
				return true
			}
		}
		return false
	}

