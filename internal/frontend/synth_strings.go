	// ToValidUTF8 returns s with each run of invalid UTF-8 replaced by
	// replacement.
	func ToValidUTF8(s, replacement string) string {
		b := &Builder{}
		for i := 0; i < len(s); {
			dc14 := stringsDecodeRune(s[i:])
			c, size := rune(dc14.r), dc14.size
			if c != stringsRuneError {
				i += size
				continue
			}
			dc15 := stringsDecodeRune(s[i:])
			_, wid := dc15.r, dc15.size
			if wid == 1 {
				b.Grow(len(s) + len(replacement))
				b.writeString(s[:i])
				s = s[i:]
				break
			}
			i += wid
		}
		if b.Cap() == 0 {
			return s
		}
		invalid := false
		for i := 0; i < len(s); {
			c := s[i]
			if c < stringsRuneSelf {
				i++
				invalid = false
				b.WriteByte(c)
				continue
			}
			dc16 := stringsDecodeRune(s[i:])
			_, wid := dc16.r, dc16.size
			if wid == 1 {
				i++
				if !invalid {
					invalid = true
					b.writeString(replacement)
				}
				continue
			}
			invalid = false
			b.writeString(s[i : i+wid])
			i += wid
		}
		return b.String()
	}

