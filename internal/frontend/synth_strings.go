	func stringsBuildReplacer(oldnew []string) stringsReplacer {
		if len(oldnew) == 2 && len(oldnew[0]) > 1 {
			return stringsMakeSingleStringReplacer(oldnew[0], oldnew[1])
		}
		allNewBytes := true
		for i := 0; i < len(oldnew); i += 2 {
			if len(oldnew[i]) != 1 {
				return stringsMakeGenericReplacer(oldnew)
			}
			if len(oldnew[i+1]) != 1 {
				allNewBytes = false
			}
		}
		if allNewBytes {
			r := &stringsByteReplacer{}
			for i := 0; i < 256; i++ {
				r.repl[i] = byte(i)
			}
			for i := len(oldnew) - 2; i >= 0; i -= 2 {
				o := oldnew[i][0]
				n := oldnew[i+1][0]
				r.repl[o] = n
			}
			return r
		}
		r := &stringsByteStringReplacer{toReplace: make([]string, 0, len(oldnew)/2)}
		for i := len(oldnew) - 2; i >= 0; i -= 2 {
			o := oldnew[i][0]
			n := oldnew[i+1]
			if r.replacements[o] == nil {
				r.toReplace = append(r.toReplace, string([]byte{o}))
			}
			r.replacements[o] = []byte(n)
		}
		return r
	}

	// stringsTrieNode is a node in the generic replacer's lookup trie.
	type stringsTrieNode struct {
		value    string
		priority int
		prefix   string
		next     *stringsTrieNode
		table    []*stringsTrieNode
	}

	func (t *stringsTrieNode) add(key, val string, priority int, r *stringsGenericReplacer) {
		if key == "" {
			if t.priority == 0 {
				t.value = val
				t.priority = priority
			}
			return
		}
		if t.prefix != "" {
			var n int
			for ; n < len(t.prefix) && n < len(key); n++ {
				if t.prefix[n] != key[n] {
					break
				}
			}
			if n == len(t.prefix) {
				t.next.add(key[n:], val, priority, r)
			} else if n == 0 {
				var prefixNode *stringsTrieNode
				if len(t.prefix) == 1 {
					prefixNode = t.next
				} else {
					prefixNode = &stringsTrieNode{
						prefix: t.prefix[1:],
						next:   t.next,
					}
				}
				keyNode := &stringsTrieNode{}
				t.table = make([]*stringsTrieNode, r.tableSize)
				t.table[r.mapping[t.prefix[0]]] = prefixNode
				t.table[r.mapping[key[0]]] = keyNode
				t.prefix = ""
				t.next = nil
				keyNode.add(key[1:], val, priority, r)
			} else {
				next := &stringsTrieNode{
					prefix: t.prefix[n:],
					next:   t.next,
				}
				t.prefix = t.prefix[:n]
				t.next = next
				next.add(key[n:], val, priority, r)
			}
		} else if t.table != nil {
			m := r.mapping[key[0]]
			if t.table[m] == nil {
				t.table[m] = &stringsTrieNode{}
			}
			t.table[m].add(key[1:], val, priority, r)
		} else {
			t.prefix = key
			t.next = &stringsTrieNode{}
			t.next.add("", val, priority, r)
		}
	}

	// stringsLookupResult is the single-result variant of lookup's
	// (val, keylen, found) result (multi-result calls need WS D).
	type stringsLookupResult struct {
		val    string
		keylen int
		found  bool
	}

	// lookup descends the trie, returning the highest-priority match. The
	// root is checked up front (instead of via node-identity comparison,
	// which needs pointer comparison — WS D) and the descent loop checks
	// each child after moving.
	func (r *stringsGenericReplacer) lookup(s string, ignoreRoot bool) stringsLookupResult {
		var res stringsLookupResult
		bestPriority := 0
		node := r.root
		n := 0
		if !ignoreRoot && node.priority > bestPriority {
			bestPriority = node.priority
			res.val = node.value
			res.keylen = 0
			res.found = true
		}
		for {
			if s == "" {
				break
			}
			if node.table != nil {
				index := r.mapping[s[0]]
				if int(index) == r.tableSize {
					break
				}
				node = node.table[index]
				s = s[1:]
				n++
			} else if node.prefix != "" && HasPrefix(s, node.prefix) {
				n += len(node.prefix)
				s = s[len(node.prefix):]
				node = node.next
			} else {
				break
			}
			if node == nil {
				break
			}
			if node.priority > bestPriority {
				bestPriority = node.priority
				res.val = node.value
				res.keylen = n
				res.found = true
			}
		}
		return res
	}

	// stringsGenericReplacer is the fully generic algorithm.
	type stringsGenericReplacer struct {
		root      *stringsTrieNode
		tableSize int
		mapping   [256]byte
	}

	func stringsMakeGenericReplacer(oldnew []string) *stringsGenericReplacer {
		r := &stringsGenericReplacer{}
		for i := 0; i < len(oldnew); i += 2 {
			key := oldnew[i]
			for j := 0; j < len(key); j++ {
				r.mapping[key[j]] = 1
			}
		}
		for i := 0; i < 256; i++ {
			r.tableSize += int(r.mapping[i])
		}
		var index byte
		for i := 0; i < 256; i++ {
			if r.mapping[i] == 0 {
				r.mapping[i] = byte(r.tableSize)
			} else {
				r.mapping[i] = index
				index++
			}
		}
		r.root = &stringsTrieNode{}
	r.root.table = make([]*stringsTrieNode, r.tableSize)
		for i := 0; i < len(oldnew); i += 2 {
			r.root.add(oldnew[i], oldnew[i+1], len(oldnew)-i, r)
		}
		return r
	}

	func (r *stringsGenericReplacer) Replace(s string) string {
		b := &Builder{}
		b.Grow(len(s))
		var last int
		var prevMatchEmpty bool
		for i := 0; i <= len(s); {
			if i != len(s) && r.root.priority == 0 {
				index := int(r.mapping[s[i]])
				if index == r.tableSize || r.root.table[index] == nil {
					i++
					continue
				}
			}
			lkRes := r.lookup(s[i:], prevMatchEmpty)
			val, keylen, match := lkRes.val, lkRes.keylen, lkRes.found
			prevMatchEmpty = match && keylen == 0
			if match {
				b.writeString(s[last:i])
				b.writeString(val)
				i += keylen
				last = i
				continue
			}
			i++
		}
		if last != len(s) {
			b.writeString(s[last:])
		}
		return b.String()
	}

	// stringsSingleStringReplacer handles the single-pattern case.
	type stringsSingleStringReplacer struct {
		finder *stringFinder
		value  string
	}

	func stringsMakeSingleStringReplacer(pattern string, value string) *stringsSingleStringReplacer {
		return &stringsSingleStringReplacer{finder: makeStringFinder(pattern), value: value}
	}

	func (r *stringsSingleStringReplacer) Replace(s string) string {
		b := &Builder{}
		i, matched := 0, false
		for {
			match := r.finder.next(s[i:])
			if match == -1 {
				break
			}
			matched = true
			b.Grow(match + len(r.value))
			b.writeString(s[i : i+match])
			b.writeString(r.value)
			i += match + len(r.finder.pattern)
		}
		if !matched {
			return s
		}
		b.writeString(s[i:])
		return b.String()
	}

	// stringsByteReplacer handles single-byte to single-byte replacements.
	// stringsByteReplacer wraps its table in a struct: index assignment
	// through a pointer-to-array is WS E in v1, but indexing a struct
	// field through a pointer is fine.
	type stringsByteReplacer struct {
		repl [256]byte
	}

	func (r *stringsByteReplacer) Replace(s string) string {
		var buf []byte
		for i := 0; i < len(s); i++ {
			b := s[i]
			if r.repl[b] != b {
				if buf == nil {
					buf = []byte(s)
				}
				buf[i] = r.repl[b]
			}
		}
		if buf == nil {
			return s
		}
		return string(buf)
	}

	// stringsByteStringReplacer handles single-byte olds with varying new sizes.
	type stringsByteStringReplacer struct {
		replacements [256][]byte
		toReplace    []string
	}

	const stringsCountCutOff = 8

	func (r *stringsByteStringReplacer) Replace(s string) string {
		newSize := len(s)
		anyChanges := false
		if len(r.toReplace)*stringsCountCutOff <= len(s) {
			for _, x := range r.toReplace {
				if c := Count(s, x); c != 0 {
					newSize += c * (len(r.replacements[x[0]]) - 1)
					anyChanges = true
				}
			}
		} else {
			for i := 0; i < len(s); i++ {
				b := s[i]
				if r.replacements[b] != nil {
					newSize += len(r.replacements[b]) - 1
					anyChanges = true
				}
			}
		}
		if !anyChanges {
			return s
		}
		buf := make([]byte, newSize)
		j := 0
		for i := 0; i < len(s); i++ {
			b := s[i]
			if r.replacements[b] != nil {
				j += copy(buf[j:], r.replacements[b])
			} else {
				buf[j] = b
				j++
			}
		}
		return string(buf)
	}
