	// Replace returns s with the first n non-overlapping instances of old
	// replaced by new.
	func Replace(s, old, new string, n int) string {
		if old == new || n == 0 {
			return s
		}
		m := Count(s, old)
		if m == 0 {
			return s
		}
		if n < 0 || m < n {
			n = m
		}
		b := &Builder{}
		b.Grow(len(s) + n*(len(new)-len(old)))
		start := 0
		if len(old) > 0 {
			for i := 0; i < n; i++ {
				j := start + Index(s[start:], old)
				b.writeString(s[start:j])
				b.writeString(new)
				start = j + len(old)
			}
		} else {
			b.writeString(new)
			for i := 0; i < n-1; i++ {
				dc20 := stringsDecodeRune(s[start:])
				_, wid := dc20.r, dc20.size
				j := start + wid
				b.writeString(s[start:j])
				b.writeString(new)
				start = j
			}
		}
		b.writeString(s[start:])
		return b.String()
	}

	// ReplaceAll returns s with all non-overlapping instances of old replaced
	// by new.
	func ReplaceAll(s, old, new string) string {
		return Replace(s, old, new, -1)
	}

	// EqualFold reports whether s and t are equal under simple Unicode
	// case-folding. Ported from strings.go (the goto-based ASCII/Unicode
	// split restructured as a flag; behavior identical).
	func EqualFold(s, t string) bool {
		i := 0
		n := len(s)
		if len(t) < n {
			n = len(t)
		}
		unicode := false
		for ; i < n; i++ {
			sr := s[i]
			tr := t[i]
			if sr|tr >= stringsRuneSelf {
				unicode = true
				break
			}
			if tr == sr {
				continue
			}
			if tr < sr {
				tr, sr = sr, tr
			}
			if 'A' <= sr && sr <= 'Z' && tr == sr+'a'-'A' {
				continue
			}
			return false
		}
		if !unicode {
			return len(s) == len(t)
		}
		s = s[i:]
		t = t[i:]
		for len(s) > 0 {
			dc21 := stringsDecodeRune(s)
			sr, ssz := rune(dc21.r), dc21.size
			s = s[ssz:]
			if len(t) == 0 {
				return false
			}
			dc22 := stringsDecodeRune(t)
			tr, tsz := rune(dc22.r), dc22.size
			t = t[tsz:]
			if tr == sr {
				continue
			}
			if tr < sr {
				tr, sr = sr, tr
			}
			if tr < stringsRuneSelf {
				if 'A' <= sr && sr <= 'Z' && tr == sr+'a'-'A' {
					continue
				}
				return false
			}
			r := stringsSimpleFold(sr)
			for r != sr && r < tr {
				r = stringsSimpleFold(r)
			}
			if r == tr {
				continue
			}
			return false
		}
		return len(t) == 0
	}

	// Compare returns -1/0/+1 comparing a and b lexicographically.
	func Compare(a, b string) int {
		n := len(a)
		if len(b) < n {
			n = len(b)
		}
		for i := 0; i < n; i++ {
			if a[i] != b[i] {
				if a[i] < b[i] {
					return -1
				}
				return 1
			}
		}
		switch {
		case len(a) < len(b):
			return -1
		case len(a) > len(b):
			return 1
		}
		return 0
	}

	// Clone returns a fresh copy of s. (copy(dst, string) is WS D, so the
	// copy is a manual loop.)
	func Clone(s string) string {
		if len(s) == 0 {
			return ""
		}
		b := make([]byte, len(s))
		for i := 0; i < len(s); i++ {
			b[i] = s[i]
		}
		return string(b)
	}

