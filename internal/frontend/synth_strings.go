	// TrimLeftFunc returns s with all leading code points satisfying f(c)
	// removed.
	func TrimLeftFunc(s string, f func(rune) bool) string {
		i := stringsIndexFunc(s, f, false)
		if i == -1 {
			return ""
		}
		return s[i:]
	}

	// TrimRightFunc returns s with all trailing code points satisfying f(c)
	// removed.
	func TrimRightFunc(s string, f func(rune) bool) string {
		return stringsTrimRightFunc(s, f)
	}

	func stringsTrimRightFunc(s string, f func(rune) bool) string {
		i := stringsLastIndexFunc(s, f, false)
		if i >= 0 {
			dc19 := stringsDecodeRune(s[i:])
			_, wid := dc19.r, dc19.size
			i += wid
		} else {
			i++
		}
		return s[0:i]
	}

	// TrimFunc returns s with all leading and trailing code points satisfying
	// f(c) removed.
	func TrimFunc(s string, f func(rune) bool) string {
		return stringsTrimRightFunc(TrimLeftFunc(s, f), f)
	}

