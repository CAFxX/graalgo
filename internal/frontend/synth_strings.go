	// Count counts the number of non-overlapping instances of substr in s.
	// If substr is empty, Count returns 1 + the number of Unicode code points
	// in s.
	func Count(s, substr string) int {
		if len(substr) == 0 {
			return stringsRuneCount(s) + 1
		}
		if len(substr) == 1 {
			return stringsCountByte(s, substr[0])
		}
		n := 0
		for {
			i := Index(s, substr)
			if i == -1 {
				return n
			}
			n++
			s = s[i+len(substr):]
		}
	}

	func stringsCountByte(s string, c byte) int {
		n := 0
		for i := 0; i < len(s); i++ {
			if s[i] == c {
				n++
			}
		}
		return n
	}

	// Contains reports whether substr is within s.
	func Contains(s, substr string) bool {
		return Index(s, substr) >= 0
	}

	// ContainsAny reports whether any Unicode code points in chars are within s.
	func ContainsAny(s, chars string) bool {
		return IndexAny(s, chars) >= 0
	}

	// ContainsRune reports whether the Unicode code point r is within s.
	func ContainsRune(s string, r rune) bool {
		return IndexRune(s, r) >= 0
	}

	// ContainsFunc reports whether any Unicode code points r within s satisfy
	// f(r).
	func ContainsFunc(s string, f func(rune) bool) bool {
		return IndexFunc(s, f) >= 0
	}

	// stringFinder is the Boyer-Moore searcher, ported from search.go.
	type stringFinder struct {
		pattern string
		badCharSkip [256]int
		goodSuffixSkip []int
	}

	func makeStringFinder(pattern string) *stringFinder {
		f := &stringFinder{
			pattern:        pattern,
			goodSuffixSkip: make([]int, len(pattern)),
		}
		last := len(pattern) - 1
		for i := 0; i < 256; i++ {
			f.badCharSkip[i] = len(pattern)
		}
		for i := 0; i < last; i++ {
			f.badCharSkip[pattern[i]] = last - i
		}
		lastPrefix := last
		for i := last; i >= 0; i-- {
			if HasPrefix(pattern, pattern[i+1:]) {
				lastPrefix = i + 1
			}
			f.goodSuffixSkip[i] = lastPrefix + last - i
		}
		for i := 0; i < last; i++ {
			lenSuffix := stringsLongestCommonSuffix(pattern, pattern[1:i+1])
			if pattern[i-lenSuffix] != pattern[last-lenSuffix] {
				f.goodSuffixSkip[last-lenSuffix] = lenSuffix + last - i
			}
		}
		return f
	}

	func stringsLongestCommonSuffix(a, b string) (i int) {
		for ; i < len(a) && i < len(b); i++ {
			if a[len(a)-1-i] != b[len(b)-1-i] {
				break
			}
		}
		return
	}

	// next returns the index in text of the first occurrence of the pattern,
	// or -1.
	func (f *stringFinder) next(text string) int {
		i := len(f.pattern) - 1
		for i < len(text) {
			j := len(f.pattern) - 1
			for j >= 0 && text[i] == f.pattern[j] {
				i--
				j--
			}
			if j < 0 {
				return i + 1
			}
			skip := f.badCharSkip[text[i]]
			if gs := f.goodSuffixSkip[j]; gs > skip {
				skip = gs
			}
			i += skip
		}
		return -1
	}

	// Index returns the index of the first instance of substr in s, or -1.
	// Ported from internal/stringslite.Index (bytealg fast paths replaced by
	// the same skip structure over IndexByte plus a Boyer-Moore fallback;
	// observable behavior is identical).
	func Index(s, substr string) int {
		n := len(substr)
		switch {
		case n == 0:
			return 0
		case n == 1:
			return IndexByte(s, substr[0])
		case n == len(s):
			if substr == s {
				return 0
			}
			return -1
		case n > len(s):
			return -1
		}
		c0 := substr[0]
		c1 := substr[1]
		i := 0
		t := len(s) - n + 1
		fails := 0
		for i < t {
			if s[i] != c0 {
				o := IndexByte(s[i+1:t], c0)
				if o < 0 {
					return -1
				}
				i += o + 1
			}
			if s[i+1] == c1 && s[i:i+n] == substr {
				return i
			}
			i++
			fails++
			if fails >= 4+i>>4 && i < t {
				j := makeStringFinder(substr).next(s[i:])
				if j < 0 {
					return -1
				}
				return i + j
			}
		}
		return -1
	}

	// LastIndex returns the index of the last instance of substr in s, or -1.
	// Implemented by Boyer-Moore search on the byte-reversed strings (the
	// first match in the reversed text is the last match in s).
	func LastIndex(s, substr string) int {
		n := len(substr)
		switch {
		case n == 0:
			return len(s)
		case n == 1:
			return LastIndexByte(s, substr[0])
		case n == len(s):
			if substr == s {
				return 0
			}
			return -1
		case n > len(s):
			return -1
		}
		rs := stringsReverse(s)
		rsub := stringsReverse(substr)
		if j := makeStringFinder(rsub).next(rs); j >= 0 {
			return len(s) - n - j
		}
		return -1
	}

	func stringsReverse(s string) string {
		b := make([]byte, len(s))
		for i := 0; i < len(s); i++ {
			b[len(s)-1-i] = s[i]
		}
		return string(b)
	}

	// IndexByte returns the index of the first instance of c in s, or -1.
	func IndexByte(s string, c byte) int {
		for i := 0; i < len(s); i++ {
			if s[i] == c {
				return i
			}
		}
		return -1
	}

	// LastIndexByte returns the index of the last instance of c in s, or -1.
	func LastIndexByte(s string, c byte) int {
		for i := len(s) - 1; i >= 0; i-- {
			if s[i] == c {
				return i
			}
		}
		return -1
	}

	// IndexRune returns the index of the first instance of the Unicode code
	// point r, or -1. Ported from strings.go (the bytealg two-phase search
	// replaced by Index over the rune's encoding, which is behaviorally
	// identical: UTF-8 lead bytes cannot appear inside another encoding).
	func IndexRune(s string, r rune) int {
		switch {
		case 0 <= r && r < stringsRuneSelf:
			return IndexByte(s, byte(r))
		case r == stringsRuneError:
			for i := 0; i < len(s); {
				dc3 := stringsDecodeRune(s[i:])
				c, size := rune(dc3.r), dc3.size
				if c == stringsRuneError {
					return i
				}
				i += size
			}
			return -1
		case r < 0 || r > stringsMaxRune:
			return -1
		default:
			return Index(s, string(r))
		}
	}

	// IndexAny returns the index of the first instance of any Unicode code
	// point from chars in s, or -1.
	func IndexAny(s, chars string) int {
		if chars == "" {
			return -1
		}
		if len(chars) == 1 {
			r := rune(chars[0])
			if r >= stringsRuneSelf {
				r = stringsRuneError
			}
			return IndexRune(s, r)
		}
		if stringsShouldUseASCIISet(len(s)) {
			msetRes := stringsMakeASCIISet(chars)
			if msetRes.ok {
				as := msetRes.as
				for i := 0; i < len(s); i++ {
					if as.stringsContains(s[i]) {
						return i
					}
				}
				return -1
			}
		}
		for i := 0; i < len(s); {
			dc4 := stringsDecodeRune(s[i:])
			c, size := rune(dc4.r), dc4.size
			if IndexRune(chars, c) >= 0 {
				return i
			}
			i += size
		}
		return -1
	}

	// LastIndexAny returns the index of the last instance of any Unicode code
	// point from chars in s, or -1.
	func LastIndexAny(s, chars string) int {
		if chars == "" {
			return -1
		}
		if len(s) == 1 {
			rc := rune(s[0])
			if rc >= stringsRuneSelf {
				rc = stringsRuneError
			}
			if IndexRune(chars, rc) >= 0 {
				return 0
			}
			return -1
		}
		if stringsShouldUseASCIISet(len(s)) {
			msetRes := stringsMakeASCIISet(chars)
			if msetRes.ok {
				as := msetRes.as
				for i := len(s) - 1; i >= 0; i-- {
					if as.stringsContains(s[i]) {
						return i
					}
				}
				return -1
			}
		}
		if len(chars) == 1 {
			rc := rune(chars[0])
			if rc >= stringsRuneSelf {
				rc = stringsRuneError
			}
			for i := len(s); i > 0; {
				dc5 := stringsDecodeLastRune(s[:i])
				r, size := rune(dc5.r), dc5.size
				i -= size
				if rc == r {
					return i
				}
			}
			return -1
		}
		for i := len(s); i > 0; {
			dc6 := stringsDecodeLastRune(s[:i])
			r, size := rune(dc6.r), dc6.size
			i -= size
			if IndexRune(chars, r) >= 0 {
				return i
			}
		}
		return -1
	}

	// IndexFunc returns the index of the first Unicode code point satisfying
	// f(c), or -1.
	func IndexFunc(s string, f func(rune) bool) int {
		return stringsIndexFunc(s, f, true)
	}

	// LastIndexFunc returns the index of the last Unicode code point
	// satisfying f(c), or -1.
	func LastIndexFunc(s string, f func(rune) bool) int {
		return stringsLastIndexFunc(s, f, true)
	}

	func stringsIndexFunc(s string, f func(rune) bool, truth bool) int {
		for i := 0; i < len(s); {
			dc7 := stringsDecodeRune(s[i:])
			r, size := rune(dc7.r), dc7.size
			if f(r) == truth {
				return i
			}
			i += size
		}
		return -1
	}

	func stringsLastIndexFunc(s string, f func(rune) bool, truth bool) int {
		for i := len(s); i > 0; {
			dc8 := stringsDecodeLastRune(s[:i])
			r, size := rune(dc8.r), dc8.size
			i -= size
			if f(r) == truth {
				return i
			}
		}
		return -1
	}

