	// (rune, bool) result (multi-result calls need WS D).
	type stringsToResult struct {
		r  int64
		ok bool
	}

	func stringsTo(_case int, r rune) stringsToResult {
		if _case < 0 || stringsMaxCase <= _case {
			return stringsToResult{int64(stringsRuneError), false}
		}
		if idx := stringsCaseRangeIndex(r); idx >= 0 {
			return stringsToResult{int64(stringsConvertCase(_case, r, stringsCaseRanges[idx])), true}
		}
		return stringsToResult{int64(r), false}
	}

	// stringsToUpper maps r to upper case (unicode.ToUpper).
	func stringsToUpper(r rune) rune {
		r = rune(stringsTo(stringsUpperCase, r).r)
		return r
	}

	// stringsToLower maps r to lower case (unicode.ToLower).
	func stringsToLower(r rune) rune {
		r = rune(stringsTo(stringsLowerCase, r).r)
		return r
	}

	// stringsToTitle maps r to title case (unicode.ToTitle).
	func stringsToTitle(r rune) rune {
		r = rune(stringsTo(stringsTitleCase, r).r)
		return r
	}

	// stringsSimpleFold iterates over code points equivalent under simple case
	// folding (port of unicode.SimpleFold).
	func stringsSimpleFold(r rune) rune {
		if r < 0 || r > stringsMaxRune {
			return r
		}
		if int(r) < len(stringsASCIIFold) {
			return rune(stringsASCIIFold[r])
		}
		lo := 0
		hi := len(stringsCaseOrbit)
		for lo < hi {
			m := int(uint(lo+hi) >> 1)
			if rune(stringsCaseOrbit[m][0]) < r {
				lo = m + 1
			} else {
				hi = m
			}
		}
		if lo < len(stringsCaseOrbit) && rune(stringsCaseOrbit[lo][0]) == r {
			return rune(stringsCaseOrbit[lo][1])
		}
		if idx := stringsCaseRangeIndex(r); idx >= 0 {
			cr := stringsCaseRanges[idx]
			if l := stringsConvertCase(stringsLowerCase, r, cr); l != r {
				return l
			}
			return stringsConvertCase(stringsUpperCase, r, cr)
		}
		return r
	}

