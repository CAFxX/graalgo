// the overlay importer, so the context source's `import "time"` resolves
// to the synthetic package (synthetic→synthetic imports).
// The same *types.Package instance is returned to every importer, so
// *types.Func/*types.TypeName objects are identical between the user's
// type-check and the synthetic sources' own.
func getSyntheticPackage(path string) *syntheticPackage {
	synthMu.Lock()
	if sp, ok := synthCache[path]; ok {
		synthMu.Unlock()
		return sp
	}
	synthMu.Unlock()
	sp := buildSyntheticPackage(path)
	synthMu.Lock()
	defer synthMu.Unlock()
	if prev, ok := synthCache[path]; ok {
		return prev
	}
	synthCache[path] = sp
	return sp
}

func buildSyntheticPackage(path string) *syntheticPackage {
	src, ok := syntheticSources[path]
	if !ok {
		panic("gofrontend: no synthetic source for " + path)
	}
	fset := token.NewFileSet()
	// P3-M8 (wave 2): ParseComments populates doc comments so the
	// //go:linkname directives in synthetic sources (os) are visible to
	// the exporter's linkname scan (ADR-0004 D1); matches ExportFile.
	file, err := parser.ParseFile(fset, path+".go", src, parser.AllErrors|parser.ParseComments)
	if err != nil {
		panic("gofrontend: synthetic " + path + " parse error: " + err.Error())
	}
	info := &types.Info{
		Types:      make(map[ast.Expr]types.TypeAndValue),
		Defs:       make(map[*ast.Ident]types.Object),
		Uses:       make(map[*ast.Ident]types.Object),
		Selections: make(map[*ast.SelectorExpr]*types.Selection),
		Implicits:  make(map[ast.Node]types.Object),
		Instances:  make(map[*ast.Ident]types.Instance),
	}
	conf := types.Config{Importer: overlayImporter{}}
	pkg, err := conf.Check(path, fset, []*ast.File{file}, info)
	if err != nil {
		panic("gofrontend: synthetic " + path + " type error: " + err.Error())
	}
	return &syntheticPackage{
		path: path, src: src, pkg: pkg,
		files: []*ast.File{file}, info: info, fset: fset,
		raw: []byte(src),
	}
}

// timeIntrinsicNames are the synthetic time package's clock/timer entry
// points (ADR-0005 D1): declared with exact gc signatures, always
// intercepted into the §D3 wire nodes, never exported as funcdecls.
var timeIntrinsicNames = map[string]bool{
	"Now": true, "Sleep": true, "After": true, "Tick": true,
	"NewTimer": true, "NewTicker": true, "AfterFunc": true,
}

// isSyntheticIntrinsic reports whether a synthetic package declaration is
// an intrinsic (intercepted at call sites, no funcdecl emitted).
func isSyntheticIntrinsic(path, name string) bool {
	if path == "time" {
		return timeIntrinsicNames[name]
	}
	if path == "math" {
		return mathIntrinsicNames[name]
	}
	if path == "reflect" {
		return reflectIntrinsicNames[name]
	}
	return false
}

// timeTimerTickerNamed reports whether t unwraps (through one pointer) to
// the synthetic time.Timer or time.Ticker named type.
func timeTimerTickerNamed(t types.Type) *types.Named {
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	return timeTimerTickerNamedExact(t)
}

// timeTimerTickerNamedExact is timeTimerTickerNamed without pointer
// dereference: for value positions (var declarations, composite
// literals, struct fields, slice/array/map elements) where *time.Timer
// is legal but time.Timer is not in M5 scope.
func timeTimerTickerNamedExact(t types.Type) *types.Named {
	nt, ok := t.(*types.Named)
	if !ok {
		return nil
	}
	obj := nt.Obj()
	if obj == nil || obj.Pkg() == nil || obj.Pkg().Path() != "time" {
		return nil
	}
	if obj.Name() != "Timer" && obj.Name() != "Ticker" {
		return nil
	}
	return nt
}

// synthGroup is one synthetic package's declarations imported into the
// document.
type synthGroup struct {
	sp  *syntheticPackage
	fis []*funcDeclInfo
}

// importSyntheticPackage merges a synthetic package's real-Go
// declarations into the document: package vars become globals (emitted
// immediately, in source order — they cannot depend on user vars),
// funcs/methods populate funcByObj/methodIndex (their bodies are emitted
// later by exportSyntheticBodies). Intrinsics are skipped. The exporter's
// per-file state is swapped for the duration.
func (e *exporter) importSyntheticPackage(sp *syntheticPackage) error {
	// P3-M8: idempotent — skip if already imported (prevents duplicate
	// globals when e.g. errors is imported both directly and via io).
	if e.importedSynthetic[sp.path] {
		return nil
	}
	e.importedSynthetic[sp.path] = true
	savedFset, savedSrc, savedInfo, savedPkg := e.fset, e.src, e.info, e.pkg
	savedSubst, savedSubstTypeIDs := e.subst, e.substTypeIDs
	e.fset, e.src, e.info, e.pkg = sp.fset, sp.raw, sp.info, sp.pkg
	e.subst, e.substTypeIDs = nil, nil
	defer func() {
		e.fset, e.src, e.info, e.pkg = savedFset, savedSrc, savedInfo, savedPkg
		e.subst, e.substTypeIDs = savedSubst, savedSubstTypeIDs
	}()
	g := synthGroup{sp: sp}
	// Two passes: funcs first (so var initializers can call them),
	// then package vars.
	// Within funcs: two sub-passes. Pass 1 registers all funcDeclInfos
	// in the maps (without calling defFunc). Pass 2 calls defFunc for
	// each. This is needed because defFunc triggers type description,
	// which can build method tables, which can call multiResultHelperFunc,
	// which looks up helpers in synthFuncIDs. If a helper is defined
	// later in the file than a method whose table needs it, single-pass
	// ordering fails (the lookup happens before registration).
	type synthFuncEntry struct {
		obj *types.Func
		fi  *funcDeclInfo
	}
	var funcEntries []*synthFuncEntry
	for _, file := range sp.files {
		for _, decl := range file.Decls {
			d, ok := decl.(*ast.FuncDecl)
			if !ok {
				continue
			}
			obj, ok := e.info.Defs[d.Name].(*types.Func)
			if !ok {
				return scopeErrorf("synthetic %s: %s has no *types.Func object", sp.path, d.Name.Name)
			}
			// Intrinsics are package-level functions only; methods with the
			// same name (e.g. Time.After vs time.After) are real methods.
			if d.Recv == nil && isSyntheticIntrinsic(sp.path, obj.Name()) {
				continue
			}
			sig, ok := obj.Type().(*types.Signature)
			if !ok {
				return scopeErrorf("synthetic %s: %s has non-signature type", sp.path, obj.Name())
			}
			// P3-M5 (WS E, ADR-0005): multi-result declarations
			// (Context.Deadline, time.ParseDuration, Time.Date/Clock/Zone)
			// are declared with exact gc signatures for type-checking,
			// but v1 cannot emit or call multi-result functions (WS D;
			// the P3-M3 F4 fail-fast precedent). They are skipped here —
			// never in funcByObj/methodIndex. The Appendix M desugar avoids
			// interface conversions (uses concrete *cancelCtx/*timerCtx
			// directly), so P3-M3 method tables do not need the multi-result
			// Deadline methods. Every call site fails fast with a named M5
			// scope error (see isMultiResultSynthetic), or is desugared.
			if sig.Results().Len() > 1 {
				// P3-M9 (math/big): multi-result METHODS are added to
				// methodIndex (so the AST walk's resolveMethodCall
				// succeeds) but never emitted. The Appendix M desugar
				// intercepts call sites via the table; the stub body is
				// fail-fast and never emitted. Package-level multi-result
				// funcs are still skipped (no methodIndex entry needed).
				// P3-M9 (RC-6): bodyless multi-result methods carrying
				// //go:linkname (e.g. fmtstate.PrinterState.Write) ARE
				// emitted via exportLinknameDecl — they bind to Java
				// intrinsics, not Go bodies, so the multi-result emission
				// limit doesn't apply. Fall through to normal processing.
				if d.Body == nil {
					// Fall through to normal processing (do not continue).
				} else {
					if d.Recv != nil {
						recv := sig.Recv()
						if recv != nil {
							if rn := derefNamed(recv.Type()); rn != nil {
								// Dummy entry: the desugar intercepts all
								// call sites, so this is never emitted.
								e.methodIndex[methodKey{rn.Obj(), obj.Name()}] = &funcDeclInfo{fd: d, obj: obj, sig: sig}
							}
						}
					}
					continue
				}
			}
			// Pass 1: create fi and register in maps (defFunc deferred to
			// pass 2 below).
			fi := &funcDeclInfo{fd: d, obj: obj, funcID: -1, sig: sig, file: file}
			if d.Recv != nil {
				recv := sig.Recv()
				if recv == nil {
					return scopeErrorf("synthetic %s: method %s has no receiver var", sp.path, obj.Name())
				}
				fi.recv = recv
				rn := derefNamed(recv.Type())
				if rn == nil {
					return scopeErrorf("synthetic %s: method %s has non-named receiver type", sp.path, obj.Name())
				}
				// For methods, methodIndex is populated here (dummy for
				// multi-result is handled above; this is for single-result).
				// Note: multi-result methods were already 'continue'd above.
				e.methodIndex[methodKey{rn.Obj(), obj.Name()}] = fi
				fi.isTemplate = sig.TypeParams().Len() > 0 || rn.Origin().TypeParams().Len() > 0
			} else {
				fi.isTemplate = sig.TypeParams().Len() > 0
			}
			fi.synthPkg = sp
			e.funcByObj[obj] = fi
			if e.synthFuncIDs == nil {
				e.synthFuncIDs = make(map[string]*funcDeclInfo)
			}
			e.synthFuncIDs[sp.path+"."+obj.Name()] = fi
			g.fis = append(g.fis, fi)
			// Defer defFunc to pass 2 (see above).
			funcEntries = append(funcEntries, &synthFuncEntry{obj: obj, fi: fi})
		}
	}
	// Pass 2: call defFunc for each registered function. Now safe because
	// all helpers are already in synthFuncIDs/funcByObj, so any method
	// table building triggered by type description will find them.
	// WS G: e.src follows the declaration's own file (multi-file disk
	// packages); e.pos() indexes e.src by per-file fset offsets.
	for _, fe := range funcEntries {
		e.src = sp.srcForFile(fe.fi.file)
		funcID, err := e.defFunc(fe.obj)
		if err != nil {
			return err
		}
		fe.fi.funcID = funcID
	}
	// Package vars, in dependency order (M7): an initializer may read
	// another package-level var declared LATER in the source (e.g. the
	// synthetic unicode package's Categories map reads the C/Cc/... aliases
	// declared later, like the json package's jsonOverThresh/jsonPow2str)
	// — the same topological sort as user package vars (Go spec, Package
	// initialization). e.info is the synthetic package's info here
	// (swapped above), so dependency analysis resolves correctly.
	// Two passes, mirroring collectPackageVars/exportPackageVars: pass 1
	// defines every var (so initializers may reference vars declared
	// later); pass 2 exports the initializers.
	type synthVarSpec struct {
		vs   *ast.ValueSpec
		oids []int
		file *ast.File
	}
	var sspecs []synthVarSpec
	for _, file := range sp.files {
		// WS G: per-file source for e.pos() (see Pass 2 above).
		e.src = sp.srcForFile(file)
		for _, decl := range file.Decls {
			d, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			switch d.Tok {
			case token.VAR:
				for _, spec := range d.Specs {
					vs, ok := spec.(*ast.ValueSpec)
					if !ok {
						return scopeErrorf("synthetic %s: package-level var spec %T is not supported", sp.path, spec)
					}
					if len(vs.Values) != 0 && len(vs.Values) != len(vs.Names) {
						return scopeErrorf("synthetic %s: var spec with %d names and %d values is not supported",
							sp.path, len(vs.Names), len(vs.Values))
					}
					sv := synthVarSpec{vs: vs, file: file}
					for _, n := range vs.Names {
						if n.Name == "_" {
							sv.oids = append(sv.oids, -1)
							continue
						}
						v, ok := e.info.Defs[n].(*types.Var)
						if !ok {
							return scopeErrorf("synthetic %s: package var %q has no *types.Var object", sp.path, n.Name)
						}
						oid, err := e.defVar(v, false)
						if err != nil {
							return err
						}
						// P3-M9: record in synthVarIDs for cross-package var
						// references (type-checked in isolation, pointers not
						// shared). Key: package path + "." + var name.
						if e.synthVarIDs == nil {
							e.synthVarIDs = make(map[string]int)
						}
						e.synthVarIDs[sp.path+"."+n.Name] = oid
						sv.oids = append(sv.oids, oid)
					}
					sspecs = append(sspecs, sv)
				}
			case token.CONST, token.TYPE, token.IMPORT:
				// Consts fold via go/types; named types register
				// lazily; imports carry no code.
			default:
				return scopeErrorf("synthetic %s: package-level %v is not supported", sp.path, d.Tok)
			}
		}
	}
	varInits := []ginit{}
	for _, sv := range sspecs {
		// WS G: the initializer's own file (multi-file disk packages).
		e.src = sp.srcForFile(sv.file)
		for i, n := range sv.vs.Names {
			if n.Name == "_" {
				continue
			}
			var init *Node
			var initExpr ast.Expr
			if len(sv.vs.Values) > 0 {
				initExpr = sv.vs.Values[i]
				x, err := e.exportExpr(initExpr)
				if err != nil {
					return err
				}
				init = x
			} else {
				// P3-M9: synthetic package `var x sync.Once` (no init)
				// normalizes to an implicit syncnew — mirrors the user
				// package path (export.go). Without it the frozen
				// factory's struct zero (GoStruct) would be installed
				// and method calls would CCE (GoStruct cannot be cast
				// to GoOnce).
				if v, ok := e.info.Defs[n].(*types.Var); ok {
					if nt := syntheticPrimitiveNamed(v.Type()); nt != nil {
						tid, err := e.typeID(v.Type())
						if err != nil {
							return err
						}
						init = e.node("syncnew", sv.vs, map[string]any{
							"synctyp": syntheticOpTypeName(nt), "type": tid,
						})
					}
				}
			}
			varInits = append(varInits, ginit{oid: sv.oids[i], init: init, expr: initExpr, pos: e.pos(n)})
		}
	}
	depFuncs := make(map[*types.Func]*ast.FuncDecl, len(g.fis))
	for _, fi := range g.fis {
		depFuncs[fi.obj] = fi.fd
	}
	// P3-M9 (BUG-MODPROBE-009): the disk multi-result transformation
	// splits F into a __F helper (real body) + F stub (panic body), and
	// the stub is skipped from g.fis above. But package-var initializers
	// reference the STUB name, so orderVarInits' transitive scan would
	// see only the panic body and miss real dependencies (e.g. uuid's
	// NameSpaceDNS = Must(Parse(...)) must follow xvalues, which Parse
	// reaches via xtob). Map each stub's func object to its helper's
	// body so the dependency analysis follows the real implementation.
	// Interface-method specs have no helper/stub and are skipped.
	for i := range diskMRSpecs {
		spec := &diskMRSpecs[i]
		if spec.pkgPath != sp.path || spec.helper == "" || spec.stub == nil {
			continue
		}
		stubFn, ok := e.info.Defs[spec.stub.Name].(*types.Func)
		if !ok {
			continue
		}
		for _, fi := range g.fis {
			if fi.obj.Name() == spec.helper {
				depFuncs[stubFn] = fi.fd
				break
			}
		}
	}
	ordered, err := orderVarInits(varInits, e.info, e.objIDs, func(oid int) string {
		return e.objects[oid].Name
	}, depFuncs)
	if err != nil {
		return err
	}
	for _, g := range ordered {
		e.synthGlobals = append(e.synthGlobals, GlobalEnt{Obj: g.oid, Init: g.init, Pos: g.pos})
	}
	// Go spec (Package initialization): after the package's variables
	// are initialized, its init() functions run in declaration order —
	// emitted as side-effect-only globals entries like the user
	// package's (see exportPackageVars). Load-bearing for synthetic
	// packages whose init computes package state (e.g. the nistec
	// generator tables, the bzip2 CRC table, zip's compressor
	// registry).
	for _, fi := range g.fis {
		if fi.fd.Recv == nil && fi.obj.Name() == "init" {
			// WS G: the init func's own file (multi-file disk packages).
			e.src = sp.srcForFile(fi.file)
			ent, err := e.initCallEnt(fi)
			if err != nil {
				return err
			}
			e.synthGlobals = append(e.synthGlobals, ent)
		}
	}
	e.synthGroups = append(e.synthGroups, g)
	return nil
}

// exportSyntheticBodies emits the imported synthetic funcdecls into
// doc.Funcs (after the user's). State is swapped per package.
func (e *exporter) exportSyntheticBodies(doc *Doc) error {
	for _, g := range e.synthGroups {
		savedFset, savedSrc, savedInfo, savedPkg := e.fset, e.src, e.info, e.pkg
		savedSubst, savedSubstTypeIDs := e.subst, e.substTypeIDs
		e.fset, e.src, e.info, e.pkg = g.sp.fset, g.sp.raw, g.sp.info, g.sp.pkg
		e.subst, e.substTypeIDs = nil, nil
		for _, fi := range g.fis {
			if fi.isTemplate {
				// P3-M9 (tier-1d): templates emit only via monomorphized
				// instantiations (exportInstantiation), never directly —
				// same rule as user templates.
				continue
			}
			// WS G: the declaration's own file (multi-file disk packages).
			e.src = g.sp.srcForFile(fi.file)
			f, err := e.exportFuncDecl(fi)
			if err != nil {
				e.fset, e.src, e.info, e.pkg = savedFset, savedSrc, savedInfo, savedPkg
				e.subst, e.substTypeIDs = savedSubst, savedSubstTypeIDs
				return err
			}
			doc.Funcs = append(doc.Funcs, f)
		}
		e.fset, e.src, e.info, e.pkg = savedFset, savedSrc, savedInfo, savedPkg
		e.subst, e.substTypeIDs = savedSubst, savedSubstTypeIDs
	}
	return nil
}

// syncIntrinsicNames are the synthetic sync package intrinsics (P3-M9).
// OnceFunc is the only one: it lowers to a closure capturing a fresh
// sync.Once (see exportSyncOnceFunc). All other sync members are types
// (Mutex, Once, ...) whose methods go through the syncop wire node.
var syncIntrinsicNames = map[string]bool{
	"OnceFunc": true,
}

// exportSyncIntrinsic lowers a call to a synthetic sync intrinsic into
// wire nodes.
func (e *exporter) exportSyncIntrinsic(c *ast.CallExpr, name string) (*Node, error) {
	switch name {
	case "OnceFunc":
		return e.exportSyncOnceFunc(c)
	}
	return nil, scopeErrorf("sync.%s is not a recognized intrinsic", name)
}

// exportSyncOnceFunc lowers sync.OnceFunc(f) to the equivalent of:
//
//	__once_N := new(sync.Once)  // syncnew wire node
//	__f_N := f                   // hoisted argument
//	func() { __once_N.Do(__f_N) } // funclit capturing both
//
// The temporaries are appended to e.mrHoistPre as vardecl nodes, flushed
// by exportStmt into the enclosing block (the multi-result hoist
// precedent). The returned funclit node evaluates to the GoFunc closure.
// This is a general frontend intrinsic, not x509-specific: any caller of
// sync.OnceFunc gets true once-semantics via GoOnce.doOnce.
func (e *exporter) exportSyncOnceFunc(c *ast.CallExpr) (*Node, error) {
	if len(c.Args) != 1 {
		return nil, scopeErrorf("sync.OnceFunc takes 1 argument")
	}
	args, err := e.exportCallArgs(c)
	if err != nil {
		return nil, err
	}
	fNode := args[0]
	// Result type: func(), from the call's type.
	retTid, err := e.callType(c)
	if err != nil {
		return nil, err
	}
	// The sync.Once named type, from the synthetic sync package.
	syncPkg := syntheticSyncPackage()
	onceObj := syncPkg.Scope().Lookup("Once")
	onceTN, ok := onceObj.(*types.TypeName)
	if !ok {
		return nil, fmt.Errorf("gofrontend: synthetic sync.Once is not a type name")
	}
	onceNamed, ok := onceTN.Type().(*types.Named)
	if !ok {
		return nil, fmt.Errorf("gofrontend: synthetic sync.Once is not a named type")
	}
	onceTid, err := e.typeID(onceNamed)
	if err != nil {
		return nil, err
	}
	// Argument type, for the hoisted f temporary.
	fType := e.info.Types[c.Args[0]].Type
	if fType == nil {
		return nil, fmt.Errorf("gofrontend: no type info for sync.OnceFunc argument")
	}
	fTid, err := e.typeID(fType)
	if err != nil {
		return nil, err
	}

	seq := e.syncGoSeq
	e.syncGoSeq++

	// Hoist f into a temporary so the closure captures a stable value.
	fName := fmt.Sprintf("__oncefunc_f_%d", seq)
	fVar := types.NewVar(token.NoPos, nil, fName, fType)
	fID, err := e.defVar(fVar, false)
	if err != nil {
		return nil, err
	}
	e.mrHoistPre = append(e.mrHoistPre, e.node("vardecl", c, map[string]any{
		"names": []string{fName}, "objs": []int{fID},
		"define": true, "type": nil, "values": []*Node{fNode},
	}))
	fIdent := e.node("ident", c, map[string]any{
		"name": fName, "obj": fID, "type": fTid,
	})

	// Fresh sync.Once via the syncnew wire node, hoisted into a temporary.
	onceNode := e.node("syncnew", c, map[string]any{
		"synctyp": syntheticOpTypeName(onceNamed), "type": onceTid,
	})
	onceName := fmt.Sprintf("__oncefunc_once_%d", seq)
	onceVar := types.NewVar(token.NoPos, nil, onceName, onceNamed)
	onceID, err := e.defVar(onceVar, false)
	if err != nil {
		return nil, err
	}
	e.mrHoistPre = append(e.mrHoistPre, e.node("vardecl", c, map[string]any{
		"names": []string{onceName}, "objs": []int{onceID},
		"define": true, "type": nil, "values": []*Node{onceNode},
	}))
	onceIdent := e.node("ident", c, map[string]any{
		"name": onceName, "obj": onceID, "type": onceTid,
	})

	// Closure body: __once_N.Do(__f_N), via the syncop wire node.
	// Do has no results; mirror exportSyncOpNodes' node shape.
	doNode := e.node("syncop", c, map[string]any{
		"op": "Do", "synctyp": syntheticOpTypeName(onceNamed),
		"recv": onceIdent, "args": []*Node{fIdent}, "type": nil,
	})
	body := e.node("block", c, map[string]any{
		"stmts": []*Node{e.node("exprstmt", c, map[string]any{"x": doNode})},
	})
	return e.node("funclit", c, map[string]any{
		"params": []*Node{}, "results": []*Node{}, "body": body, "type": retTid,
	}), nil
}

// exportTimeIntrinsic lowers a call to a synthetic time intrinsic
// (ADR-0005 D1) into its §D3 wire node.
func (e *exporter) exportTimeIntrinsic(c *ast.CallExpr, name string) (*Node, error) {
	args, err := e.exportCallArgs(c)
	if err != nil {
		return nil, err
	}
	typ, err := e.callType(c)
	if err != nil {
		return nil, err
	}
	return e.timeIntrinsicNode(c, name, args, typ)
}

// timeIntrinsicNode builds the wire node for a synthetic time intrinsic
// call from already-exported args. Split out of exportTimeIntrinsic so
// intrinsic values (exportTimeIntrinsicValue) can synthesize the call
// without an *ast.CallExpr.
func (e *exporter) timeIntrinsicNode(pos ast.Node, name string, args []*Node, typ any) (*Node, error) {
	duration := func() (*Node, error) {
		if len(args) != 1 {
			return nil, scopeErrorf("time.%s takes 1 argument", name)
		}
		return args[0], nil
	}
	switch name {
	case "Now":
		if len(args) != 0 {
			return nil, scopeErrorf("time.Now takes no arguments")
		}
		return e.node("timenow", pos, map[string]any{"type": typ}), nil
	case "Sleep":
		d, err := duration()
		if err != nil {
			return nil, err
		}
		return e.node("timesleep", pos, map[string]any{"duration": d}), nil
	case "After":
		d, err := duration()
		if err != nil {
			return nil, err
		}
		return e.node("timeafter", pos, map[string]any{"duration": d, "type": typ}), nil
	case "Tick":
		d, err := duration()
		if err != nil {
			return nil, err
		}
		return e.node("timetick", pos, map[string]any{"duration": d, "type": typ}), nil
	case "NewTimer":
		d, err := duration()
		if err != nil {
			return nil, err
		}
		return e.node("timenew", pos, map[string]any{"kind": "timer", "duration": d, "type": typ}), nil
	case "NewTicker":
		d, err := duration()
		if err != nil {
			return nil, err
		}
		return e.node("timenew", pos, map[string]any{"kind": "ticker", "duration": d, "type": typ}), nil
	case "AfterFunc":
		if len(args) != 2 {
			return nil, scopeErrorf("time.AfterFunc takes 2 arguments")
		}
		return e.node("timeafterfunc", pos, map[string]any{
			"duration": args[0], "func": args[1], "type": typ,
		}), nil
	}
	return nil, scopeErrorf("time.%s is not a recognized intrinsic", name)
}

// exportTimeIntrinsicValue lowers a synthetic time intrinsic used in value
// position (e.g. `timeNow = time.Now`) to a synthesized wrapper closure:
// func() time.Time { return time.Now() }. General: any time intrinsic, any
// arity — parameters are forwarded to the intrinsic call, and evaluation
// is deferred to call time, matching gc's func-value semantics. (The M5
// fail-fast this replaces assumed intrinsics could only be called.)
func (e *exporter) exportTimeIntrinsicValue(x *ast.SelectorExpr, obj *types.Func) (*Node, error) {
	sig, ok := obj.Type().(*types.Signature)
	if !ok {
		return nil, fmt.Errorf("gofrontend: time intrinsic %s has non-signature type %s", obj.Name(), obj.Type())
	}
	params, err := e.exportSignatureVars(x, sig.Params())
	if err != nil {
		return nil, err
	}
	// Forward the wrapper's params as the intrinsic call's args.
	args := make([]*Node, 0, len(params))
	for i := range params {
		v := sig.Params().At(i)
		oid, ok := e.objIDs[v]
		if !ok {
			return nil, fmt.Errorf("gofrontend: wrapper param %q missing from object table", v.Name())
		}
		tid, err := e.typeID(v.Type())
		if err != nil {
			return nil, err
		}
		args = append(args, e.node("ident", x, map[string]any{
			"name": v.Name(), "obj": oid, "type": tid,
		}))
	}
	var typ any
	nr := sig.Results().Len()
	if nr == 1 {
		typ, err = e.typeID(sig.Results().At(0).Type())
		if err != nil {
			return nil, err
		}
	} else if nr > 1 {
		return nil, scopeErrorf("time.%s has %d results; an intrinsic value with multiple results is not supported in frontend/v1 scope", obj.Name(), nr)
	}
	call, err := e.timeIntrinsicNode(x, obj.Name(), args, typ)
	if err != nil {
		return nil, err
	}
	results, err := e.exportSignatureVars(x, sig.Results())
	if err != nil {
		return nil, err
	}
	var stmt *Node
	if nr == 1 {
		stmt = e.node("return", x, map[string]any{"results": []*Node{call}})
	} else {
		stmt = e.node("exprstmt", x, map[string]any{"x": call})
	}
	body := e.node("block", x, map[string]any{"stmts": []*Node{stmt}})
	tid, err := e.typeID(sig)
	if err != nil {
		return nil, err
	}
	return e.node("funclit", x, map[string]any{
		"params": params, "results": results, "body": body, "type": tid,
	}), nil
}

// exportMathIntrinsic lowers a call to a synthetic math intrinsic
// (P3-M7, ADR-0007 D5) into its wire node. Each intrinsic gets its own
// wire kind (the time-intrinsic precedent): "mathf64bits",
// "mathf64frombits", "mathf32bits", "mathf32frombits", "mathsqrt",
// "mathfma". Fields: the operand expression(s) ("x" / "x","y","z") and
// "type" (result type-table id, never guessed).
func (e *exporter) exportMathIntrinsic(c *ast.CallExpr, name string) (*Node, error) {
	args, err := e.exportCallArgs(c)
	if err != nil {
		return nil, err
	}
	typ, err := e.callType(c)
	if err != nil {
		return nil, err
	}
	kind, ok := map[string]string{
		"Float64bits":     "mathf64bits",
		"Float64frombits": "mathf64frombits",
		"Float32bits":     "mathf32bits",
		"Float32frombits": "mathf32frombits",
		"Sqrt":            "mathsqrt",
		"FMA":             "mathfma",
	}[name]
	if !ok {
		return nil, scopeErrorf("math.%s is not a recognized intrinsic", name)
	}
	want := 1
	if name == "FMA" {
		want = 3
	}
	if len(args) != want {
		return nil, scopeErrorf("math.%s takes %d arguments", name, want)
	}
	fields := map[string]any{"x": args[0], "type": typ}
	if name == "FMA" {
		fields["y"] = args[1]
		fields["z"] = args[2]
	}
	return e.node(kind, c, fields), nil
}

// exportAliasIntrinsic lowers a call to crypto/internal/fips140/alias.AnyOverlap
// or InexactOverlap into the "sliceoverlap" wire node. The real package uses
// uintptr(unsafe.Pointer(...)) which traps under D5; this implements the
// overlap detection directly on the GoSlice values (array identity + range
// intersection). Fields: "x", "y" (the two []byte slices), "inexact" (bool),
// "type" (result bool type id).
func (e *exporter) exportAliasIntrinsic(c *ast.CallExpr, name string) (*Node, error) {
	args, err := e.exportCallArgs(c)
	if err != nil {
		return nil, err
	}
	if len(args) != 2 {
		return nil, scopeErrorf("alias.%s takes 2 arguments", name)
	}
	typ, err := e.callType(c)
	if err != nil {
		return nil, err
	}
	return e.node("sliceoverlap", c, map[string]any{
		"x": args[0], "y": args[1],
		"inexact": name == "InexactOverlap",
		"type":    typ,
	}), nil
}

// exportTimeOp lowers (*time.Timer).Stop/Reset and (*time.Ticker).Stop/
// Reset method calls (ADR-0005 D1) into the "timeop" wire node.
func (e *exporter) exportTimeOp(c *ast.CallExpr, sel *ast.SelectorExpr, nt *types.Named) (*Node, error) {
	op := sel.Sel.Name
	if op != "Stop" && op != "Reset" {
		return nil, scopeErrorf("time.%s.%s is not in M5 scope", nt.Obj().Name(), op)
	}
	recv, err := e.exportExpr(sel.X)
	if err != nil {
		return nil, err
	}
	fields := map[string]any{"op": op, "recv": recv}
	if op == "Reset" {
		if len(c.Args) != 1 {
			return nil, scopeErrorf("time.%s.Reset takes 1 argument", nt.Obj().Name())
		}
		d, err := e.exportExpr(c.Args[0])
		if err != nil {
			return nil, err
		}
		fields["duration"] = d
	}
	typ, err := e.callType(c)
	if err != nil {
		return nil, err
	}
	// P3-M5: Ticker.Stop() is void — omit the type field (Java side makes it
	// optional). Timer.Stop() returns bool.
	if typ != nil {
		fields["type"] = typ
	}
	return e.node("timeop", c, fields), nil
}

