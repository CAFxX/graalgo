// syntheticPackage is a parsed + type-checked synthetic package: the
// *types.Package the overlay importer hands out, plus the AST/Info the
// exporter needs to emit its real-Go declarations.
type syntheticPackage struct {
	path  string
	src   string
	pkg   *types.Package
	files []*ast.File
	info  *types.Info
	fset  *token.FileSet
	raw   []byte
	// raws parallels files for multi-file disk packages (WS G); nil for
	// embedded single-file synthetic sources (raw covers the one file).
	raws [][]byte
	// etaVarLits maps package-level Vars (e.g. path/filepath's lstat)
	// to their eta-expanded FuncLit initializers, for MR-closure-var
	// linking. Populated by etaExpandMRFuncValues (real-x509 lane).
	etaVarLits map[*types.Var]*ast.FuncLit
	// varFuncAliases maps package-level Vars (e.g. path/filepath's
	// lstat) to the multi-result *types.Func they alias (e.g.
	// os.Lstat), for direct call-site desugar without eta-expansion.
	// Populated by etaExpandMRFuncValues (real-x509 lane).
	varFuncAliases map[*types.Var]*types.Func
}

// srcForFile returns the source bytes for f: per-file bytes for disk
// packages, the single raw for embedded synthetic sources. e.pos()
// indexes e.src by per-file fset offsets, so the exporter's src swap must
// be file-aware once packages span multiple files.
func (sp *syntheticPackage) srcForFile(f *ast.File) []byte {
	for i, fi := range sp.files {
		if fi == f && i < len(sp.raws) {
			return sp.raws[i]
		}
	}
	return sp.raw
}

// srcForDecl returns the source bytes for the file containing fd.
func (sp *syntheticPackage) srcForDecl(fd *ast.FuncDecl) []byte {
	pos := fd.Pos()
	for _, f := range sp.files {
		if f.Pos() <= pos && pos < f.End() {
			return sp.srcForFile(f)
		}
	}
	return sp.raw
}

