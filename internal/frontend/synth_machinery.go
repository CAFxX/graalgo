// exportSyntheticQualified handles qualified identifiers in expression
// position: time.Second (const), context.Canceled (package var). Method
// expressions (time.Duration.String) are NOT idents on X and fall
// through to the normal path.
func (e *exporter) exportSyntheticQualified(x *ast.SelectorExpr, pkgName *types.PkgName) (*Node, error) {
	obj := e.info.Uses[x.Sel]
	switch obj := obj.(type) {
	case *types.Const:
		return e.foldedConst(x.Sel, obj.Val())
	case *types.Var:
		oid, ok := e.objIDs[obj]
		if !ok {
			// P3-M9: fallback to (package path, var name) lookup.
			// Synthetic packages are type-checked in isolation, so the
			// *types.Var pointer from the importing package's type-check
			// differs from the one registered at import time.
			if e.synthVarIDs != nil {
				key := pkgName.Imported().Path() + "." + obj.Name()
				oid, ok = e.synthVarIDs[key]
			}
		}
		if !ok {
			return nil, scopeErrorf("gofrontend: synthetic package var %s.%s missing from object table",
				pkgName.Name(), obj.Name())
		}
		t, err := e.typeID(obj.Type())
		if err != nil {
			return nil, err
		}
		return e.node("ident", x, map[string]any{"name": x.Sel.Name, "obj": oid, "type": t}), nil
	case *types.Func:
		if obj.Pkg() != nil && obj.Pkg().Path() == "time" && timeIntrinsicNames[obj.Name()] {
			// A time intrinsic in value position (e.g. `timeNow = time.Now`)
			// lowers to a synthesized wrapper closure; the call itself
			// stays a wire node inside the closure body.
			return e.exportTimeIntrinsicValue(x, obj)
		}
		if obj.Pkg() != nil && obj.Pkg().Path() == "math" && mathIntrinsicNames[obj.Name()] {
			return nil, scopeErrorf("math.%s is an intrinsic and cannot be used in value position (M7)", obj.Name())
		}
		// P3-M8b: a named synthetic function in value position (e.g.
		// sha256.New passed to hmac.New) lowers via the M6 func-value
		// path, exactly like a user-package function reference. The
		// synthetic package must already be imported (its funcs in
		// funcByObj); otherwise the M5 scope error is kept.
		if _, ok := e.funcByObj[obj]; ok {
			fields := map[string]any{"name": x.Sel.Name}
			if err := e.exportFuncValue(x.Sel, obj, fields); err != nil {
				return nil, err
			}
			return e.node("ident", x.Sel, fields), nil
		}
		return nil, scopeErrorf("%s.%s in value position is not supported in frontend/v1 scope (M5)",
			pkgName.Name(), obj.Name())
	default:
		return nil, scopeErrorf("selector %s.%s is not supported in frontend/v1 scope (M5)",
			pkgName.Name(), x.Sel.Name)
	}
}

