// exportSyntheticQualified handles qualified identifiers in expression
// position: time.Second (const), context.Canceled (package var). Method
// expressions (time.Duration.String) are NOT idents on X and fall
// through to the normal path.
func (e *exporter) exportSyntheticQualified(x *ast.SelectorExpr, pkgName *types.PkgName) (*Node, error) {
	obj := e.info.Uses[x.Sel]
	switch obj := obj.(type) {
	case *types.Const:
		return e.foldedConst(x.Sel, obj.Val())
	case *types.Var:
		oid, ok := e.objIDs[obj]
		if !ok {
			// P3-M9: fallback to (package path, var name) lookup.
			// Synthetic packages are type-checked in isolation, so the
			// *types.Var pointer from the importing package's type-check
			// differs from the one registered at import time.
			if e.synthVarIDs != nil {
				key := pkgName.Imported().Path() + "." + obj.Name()
				oid, ok = e.synthVarIDs[key]
			}
		}
		if !ok && isDedicatedSyntheticStub(pkgName.Imported().Path()) {
			// PKG-038: dedicated synthetic stubs (runtime/fmt/unsafe)
			// declare vars directly in their constructor — no synthetic
			// source, so no synthVarIDs entry. Materialize the var as a
			// real doc global on first qualified use, through the same
			// synthGlobals machinery the source-based synthetic packages
			// use (assembled into doc.Globals after all exports).
			var err error
			oid, err = e.materializeStubVar(pkgName.Imported().Path(), obj)
			if err != nil {
				return nil, err
			}
			ok = true
		}
		if !ok {
			return nil, scopeErrorf("gofrontend: synthetic package var %s.%s missing from object table",
				pkgName.Name(), obj.Name())
		}
		t, err := e.typeID(obj.Type())
		if err != nil {
			return nil, err
		}
		return e.node("ident", x, map[string]any{"name": x.Sel.Name, "obj": oid, "type": t}), nil
	case *types.Func:
		if obj.Pkg() != nil && obj.Pkg().Path() == "time" && timeIntrinsicNames[obj.Name()] {
			// A time intrinsic in value position (e.g. `timeNow = time.Now`)
			// lowers to a synthesized wrapper closure; the call itself
			// stays a wire node inside the closure body.
			return e.exportTimeIntrinsicValue(x, obj)
		}
		if obj.Pkg() != nil && obj.Pkg().Path() == "math" && mathIntrinsicNames[obj.Name()] {
			return nil, scopeErrorf("math.%s is an intrinsic and cannot be used in value position (M7)", obj.Name())
		}
		// P3-M8b: a named synthetic function in value position (e.g.
		// sha256.New passed to hmac.New) lowers via the M6 func-value
		// path, exactly like a user-package function reference. The
		// synthetic package must already be imported (its funcs in
		// funcByObj); otherwise the M5 scope error is kept.
		if _, ok := e.funcByObj[obj]; ok {
			fields := map[string]any{"name": x.Sel.Name}
			if err := e.exportFuncValue(x.Sel, obj, fields); err != nil {
				return nil, err
			}
			return e.node("ident", x.Sel, fields), nil
		}
		// P3-M10 (PKG-035): a table-driven multi-result function in value
		// position (e.g. var AcceptFunc ... = syscall.Accept) lowers to
		// its pair-returning __-helper — the same implementation a direct
		// call desugars to, so calling the value behaves exactly like the
		// direct call. This is the general mechanism for multi-result
		// function values: the value is always the pair form (cf. the
		// MR-closure-var invariant), and call sites through a variable
		// holding it desugar via the pair info linked at the variable's
		// definition (userMRVars). Fail-fast stubs (no __-helper) keep
		// the honest compile-time error below.
		if plan := e.mrPlanForFuncValue(obj); plan != nil {
			if plan.kind == mrUser {
				// Pair-transformed function: the value is the transformed
				// funcdecl itself (same as the M6 path above).
				fields := map[string]any{"name": x.Sel.Name}
				if err := e.exportFuncValue(x.Sel, obj, fields); err != nil {
					return nil, err
				}
				return e.node("ident", x.Sel, fields), nil
			}
			helperFn, err := e.multiResultHelper(plan)
			if err != nil {
				return nil, err
			}
			fi, ok := e.funcByObj[helperFn]
			if !ok {
				return nil, fmt.Errorf("gofrontend: synthetic helper %s not in funcByObj", helperFn.Name())
			}
			sigID, err := e.typeID(helperFn.Type())
			if err != nil {
				return nil, err
			}
			return e.node("ident", x.Sel, map[string]any{
				"name": helperFn.Name(), "obj": fi.funcID, "type": sigID,
			}), nil
		}
		// Fail-fast stub multi-result functions (e.g. time.ParseDuration)
		// cannot be used as values in v1: there is no __-helper to serve
		// as the pair form, so there is no honest value to emit. This is
		// a compile-time error, not a nil or panic-on-call value.
		if e.synthFuncIDs != nil && obj.Pkg() != nil {
			if _, ok := e.synthFuncIDs[obj.Pkg().Path()+"."+obj.Name()]; ok {
				return nil, scopeErrorf("%s.%s is a fail-fast stub and cannot be used in value position in frontend/v1 scope",
					pkgName.Name(), obj.Name())
			}
		}
		// Table-driven multi-result functions (e.g. os.Hostname,
		// syscall.Socket) cannot be used as values in v1 (the __-helper has
		// a different signature). This is a compile-time error, not nil:
		// emitting nil would be silently wrong and panic with a confusing
		// nil dereference at runtime.
		if obj.Pkg() != nil && hasStaticMREntry(obj.Pkg().Path(), obj.Name(), "") {
			return nil, scopeErrorf("%s.%s in value position is not supported in frontend/v1 scope (M5): multi-result function values require v2",
				pkgName.Name(), obj.Name())
		}
		return nil, scopeErrorf("%s.%s in value position is not supported in frontend/v1 scope (M5)",
			pkgName.Name(), obj.Name())
	default:
		return nil, scopeErrorf("selector %s.%s is not supported in frontend/v1 scope (M5)",
			pkgName.Name(), x.Sel.Name)
	}
}

// stubVarInit registers the gc-exact initializer for every var declared
// by a dedicated synthetic stub package (runtime/fmt/unsafe), keyed by
// package path + "." + var name. A stub var with no registered
// initializer fails loud at materialization: silently zero-initializing
// would diverge from gc's documented default.
var stubVarInit = map[string]func(e *exporter) (*Node, error){
	// gc 1.27.1, src/runtime/mprof.go:870: var MemProfileRate int = 512 * 1024.
	// Emitted as a folded "basiclit" const node (the foldedConst shape),
	// so the backend's generic global initializer handles it unchanged.
	"runtime.MemProfileRate": func(e *exporter) (*Node, error) {
		t, err := e.typeID(types.Typ[types.Int])
		if err != nil {
			return nil, err
		}
		v := constant.MakeInt64(512 * 1024)
		f32, _ := constant.Float32Val(v)
		f64, _ := constant.Float64Val(v)
		return &Node{Kind: "basiclit", Fields: map[string]any{
			"value": "", "const": v.ExactString(), "type": t,
			"f32bits": int32(math.Float32bits(f32)),
			"f64bits": int64(math.Float64bits(f64)),
		}}, nil
	},
}

// materializeStubVar allocates an object id for a dedicated-stub package
// var and appends its gc-exact initializer to e.synthGlobals (assembled
// into doc.Globals after all exports, like source-based synthetic
// globals). Idempotent per package path + var name: the stub constructor
// rebuilds the *types.Var on every import, so the key is path-qualified,
// not pointer-qualified (the synthVarIDs precedent). The registration in
// e.synthVarIDs makes later qualified uses share the one cell.
func (e *exporter) materializeStubVar(path string, v *types.Var) (int, error) {
	key := path + "." + v.Name()
	if e.synthVarIDs == nil {
		e.synthVarIDs = make(map[string]int)
	}
	if oid, ok := e.synthVarIDs[key]; ok {
		return oid, nil
	}
	initFn, ok := stubVarInit[key]
	if !ok {
		return 0, scopeErrorf("gofrontend: stub package var %s has no registered initializer", key)
	}
	oid, err := e.defVar(v, false)
	if err != nil {
		return 0, err
	}
	init, err := initFn(e)
	if err != nil {
		return 0, err
	}
	e.synthGlobals = append(e.synthGlobals, GlobalEnt{Obj: oid, Init: init})
	e.synthVarIDs[key] = oid
	return oid, nil
}

