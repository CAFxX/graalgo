# Transformations (all documented in the emitted file header):
#  1. unicode/utf8 is imported from the frontend overlay (re-ported
#     2026-11-03, REVIEW-2026-11-03-16 S9 extension: the utf8 helpers
#     were inlined as __bufio* only while unicode/utf8 was not in
