#  2. bufio.go / scan.go carried verbatim otherwise.
#  3. Multi-result METHODS (Read, Write, ReadBytes, etc.) are not
#     emittable. They are served via the Appendix M pattern:
#     __bufio<Recv><Method> single-result helpers + pair structs +
