// Plan 9 assembly strategy (P3-M6, SPEC §2.8 GG-0009, ADR-0007).
//
// The gc toolchain assembles .s/.S/.sx files with build constraints
// applied (go/build treats the three suffixes identically as assembly);
// graalgo cannot assemble any of them at all. Every buildable assembly
// file in a package the importer compiles must therefore resolve to
// exactly one inventory category:
//
//	evaporate              runtime-core asm: no Go stacks on Truffle, the
//	                       code has no meaning; Go-visible services come
//	                       from graalgo intrinsics / the Linknames registry.
//	intrinsify             atomics/bytealg: replaced by graalgo intrinsics
//	                       (cross-checked against the P3-M4 intrinsic audit).
//	emulate-then-intrinsify crypto: emulate leg runs the pure-Go generic
//	                       implementation; the intrinsify leg is a later phase.
//	jvm-math               math package: covered by JVM IEEE754.
//	unsupported            fail-fast: the build is rejected with an error
//	                       naming the file, its package, its category, and
//	                       the reason. Never silently ignored.
//
// A .s/.S/.sx file with no inventory entry is "uncategorized" and likewise fails
// the build. The inventory is generated by
// phases/phase3/stdlib-fork/gen-asm-inventory.py (pinned to go1.27.1) and
// embedded here; the generator exits non-zero on any uncategorized file,
// so toolchain drift surfaces at generation time, not as a silent gap.
//
// Production contract (ADR-0007, remediation note 2). The reject half of
// this mechanism -- the fail-fast error -- is the live production product:
// Loader.localRef and Loader.mainRef call CheckAsmFiles and deliberately
// use only its error return (if _, err := ...), because every buildable .s
// file a module-local package can contain sits outside GOROOT/src and
// fails fast before the inventory is ever consulted. The per-file
// AsmResolution payloads (category/replacement/reason) are nevertheless
// carried, not dropped: they are the contract the P3-M7+ backend will
// consume once stdlib packages become compilable (the stdlib branch of
// ResolveImport must then call CheckAsmFiles -- ADR-0007 obligation 1),
// and they are pinned per file by the test oracle
// (TestAsmCategoriesEndToEnd asserts every replaced category's
// category+replacement pointer). The inventory JSON itself is parsed
// lazily and only for in-GOROOT files, so the production fail-fast path
// never pays for -- or depends on -- the embedded inventory.

// asmInventoryJSON is declared in zz_asm_inventory_gen.go (generated by
// phases/phase3/stdlib-fork/gen-asm-inventory.py from the JSON inventory;
// //go:embed cannot reach ../../ so the generator emits the literal).

// AsmCategory is one SPEC §2.8 disposition of a Plan 9 assembly file.
type AsmCategory string

const (
	AsmEvaporate            AsmCategory = "evaporate"
	AsmIntrinsify            AsmCategory = "intrinsify"
	AsmEmulateThenIntrinsify AsmCategory = "emulate-then-intrinsify"
	AsmJVMIntrinsicMath      AsmCategory = "jvm-math"
	AsmUnsupported           AsmCategory = "unsupported"
	// AsmUncategorized is not a stored category: it is the absence of an
	// inventory entry, reported in fail-fast errors.
	AsmUncategorized AsmCategory = "uncategorized"
)

// AsmEntry is one row of the embedded inventory.
type AsmEntry struct {
	Path        string `json:"path"`        // GOROOT/src-relative, slash-separated
	Package     string `json:"package"`     // import path of the containing dir
	Category    string `json:"category"`    // one of the five stored categories
	Lines       int    `json:"lines"`       // source lines (inventory metadata)
	Replacement string `json:"replacement"` // intrinsic name / Java class / emulation note; "" for unsupported
	Reason      string `json:"reason"`       // why this category (fail-fast payload for unsupported)
}

// AsmResolution is the mechanism's verdict for one buildable .s file:
// the file is replaced (build proceeds) per Category/Replacement.
//
// Who consumes what, today: the production fail-fast consumes only the
// verdict itself (proceed vs. the error's category/reason payload); the
// test oracle (TestAsmCategoriesEndToEnd) consumes Category and
// Replacement per file to pin the inventory; the P3-M7+ backend is the
// designated consumer of the full payload (File/Package/Category/
// Replacement/Reason) once stdlib compilation lands (ADR-0007,
// remediation note 2). Until then the payload is carried deliberately,
// not accidentally -- see the production contract note above.
type AsmResolution struct {
	File        string // absolute path of the .s file
	Package     string // import path of the package being compiled
	Category    string // stored category (never "uncategorized" here)
	Replacement string // pointer to the replacement
	Reason      string // why this category
}

// asmInventoryByPath is the embedded inventory keyed by slash-separated
// GOROOT/src-relative path. Loaded once; the loader is single-threaded
// but OnceValues keeps this safe regardless.
var loadAsmInventory = sync.OnceValues(func() (map[string]AsmEntry, error) {
	var payload struct {
		GoVersion  string     `json:"go_version"`
		Categories []string   `json:"categories"`
		Files      []AsmEntry `json:"files"`
	}
	if err := json.Unmarshal(asmInventoryJSON, &payload); err != nil {
		return nil, fmt.Errorf("p3frontend: parsing embedded asm inventory: %w", err)
	}
	known := map[string]bool{}
	for _, c := range payload.Categories {
		known[c] = true
	}
	byPath := make(map[string]AsmEntry, len(payload.Files))
	for _, e := range payload.Files {
		if e.Path == "" {
			return nil, fmt.Errorf("p3frontend: asm inventory entry with empty path")
		}
		if !known[e.Category] {
			return nil, fmt.Errorf("p3frontend: asm inventory: %s has unknown category %q", e.Path, e.Category)
		}
		if _, dup := byPath[e.Path]; dup {
			return nil, fmt.Errorf("p3frontend: asm inventory: duplicate entry for %s", e.Path)
		}
		byPath[e.Path] = e
	}
	return byPath, nil
})

// ResolveAsmFile resolves one absolute .s file path to its inventory
// category. Files replaced by a category (evaporate, intrinsify,
// emulate-then-intrinsify, jvm-math) return an AsmResolution and the build
// proceeds. Files categorized "unsupported", files outside GOROOT/src,
// and files with no inventory entry ("uncategorized") fail fast: the
// error names the file path, the package, the category, and the reason.
//
// Ordering note: the outside-GOROOT check runs before the inventory is
// loaded, so module-local .s files (the only production case -- see the
// production contract note above) fail fast without the embedded
// inventory ever being parsed or consulted.
func (l *Loader) ResolveAsmFile(absPath, importPath string) (AsmResolution, error) {
	abs, err := filepath.Abs(absPath)
	if err != nil {
		abs = absPath
	}
	fail := func(category AsmCategory, reason string) (AsmResolution, error) {
		return AsmResolution{}, fmt.Errorf(
			"p3frontend: asm fail-fast: %s (package %q): category %q: %s",
			abs, importPath, string(category), reason)
	}
	srcRoot := filepath.Join(l.goroot, "src")
	rel, relErr := filepath.Rel(srcRoot, abs)
	outside := relErr != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator))
	if l.goroot == "" || outside {
		return fail(AsmUncategorized,
			fmt.Sprintf("file is outside the inventoried GOROOT/src (%s); only stdlib assembly "+
				"pinned to go1.27.1 has a disposition -- module-local Plan 9 assembly is not "+
				"supported by graalgo, rewrite in Go or via a graalgo intrinsic (SPEC §2.8 GG-0009)",
				srcRoot))
	}
	inv, err := loadAsmInventory()
	if err != nil {
		return AsmResolution{}, err
	}
	slashRel := filepath.ToSlash(rel)
	entry, ok := inv[slashRel]
	if !ok {
		return fail(AsmUncategorized,
			fmt.Sprintf("no inventory entry for %q in the go1.27.1 asm inventory -- re-run "+
				"phases/phase3/stdlib-fork/gen-asm-inventory.py on toolchain upgrade; "+
				"uncategorized assembly fails the build by design", slashRel))
	}
	if entry.Category == string(AsmUnsupported) {
		return fail(AsmUnsupported, entry.Reason)
	}
	return AsmResolution{
		File:        abs,
		Package:     importPath,
		Category:    entry.Category,
		Replacement: entry.Replacement,
		Reason:      entry.Reason,
	}, nil
}

// isAsmFile reports whether name is an assembly file the strategy
// covers. go/build treats .s, .S and .sx identically as assembly
// (go/build's fileListForExt: case ".s", ".S", ".sx"), so the loader
// must too: matching lowercase ".s" only let a build-tagged
// evil_amd64.S pass CheckAsmFiles silently (never even read).
func isAsmFile(name string) bool {
	return strings.HasSuffix(name, ".s") ||
		strings.HasSuffix(name, ".S") ||
		strings.HasSuffix(name, ".sx")
}

// CheckAsmFiles scans dir for the assembly files the loader treats as
// build inputs for its target (linux/amd64): .s/.S/.sx files passing
// the same filename-suffix and build-constraint filtering SelectFiles
// applies to .go files, verified file-for-file against go/build -- and
// resolves each via ResolveAsmFile. It returns the resolutions for every
// replaced file, or the first fail-fast error. A directory with no
// assembly files returns an empty slice and no error.
//
// The returned slice is the verified per-file disposition record: its
// consumer today is the test oracle (TestAsmCategoriesEndToEnd pins
// category+replacement per file; TestAsmNonBuildableSkipped pins the
// empty case), and its designated future consumer is the P3-M7+ backend
// (ADR-0007, remediation note 2). The two production hook sites
// (Loader.localRef, Loader.mainRef) deliberately use only the error --
// the discard is the documented production contract, not an oversight:
// on the production path every buildable .s file fails fast before the
// inventory is consulted, so no resolution is ever produced there.
//
// Fidelity note: go/build additionally gates .S/.sx on cgo -- they land
// in SFiles only when the package has cgo files (import "C"); otherwise
// they sit in IgnoredOtherFiles. The loader is deliberately stricter:
// graalgo has no cgo/gcc path at all (SPEC §3.7 GG-0058 bans import "C"
// in module code), so any constraint-selected .S/.sx file must resolve
// against the inventory or fail fast instead of being silently ignored.
func (l *Loader) CheckAsmFiles(dir, importPath string) ([]AsmResolution, error) {
	names, err := l.SelectAsmFiles(dir)
	if err != nil {
		return nil, err
	}
	var out []AsmResolution
	for _, name := range names {
		res, err := l.ResolveAsmFile(filepath.Join(dir, name), importPath)
		if err != nil {
			return nil, err
		}
		out = append(out, res)
	}
	return out, nil
}

// SelectAsmFiles returns the sorted basenames of the assembly files in
// dir selected for the loader's target: .s/.S/.sx files that are not
// _/.-prefixed and pass goodOSArchFile + shouldBuild. Split out of
// CheckAsmFiles so the oracle test can verify selection agreement with
// go/build independently of category resolution.
func (l *Loader) SelectAsmFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("p3frontend: reading dir %s: %w", dir, err)
	}
	var out []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() {
			continue
		}
		if strings.HasPrefix(name, "_") || strings.HasPrefix(name, ".") {
			continue
		}
		if !isAsmFile(name) {
			continue
		}
		if !l.goodOSArchFile(name) {
			continue
		}
		content, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, fmt.Errorf("p3frontend: reading %s: %w", name, err)
		}
		ok, err := l.shouldBuild(content)
		if err != nil {
			return nil, fmt.Errorf("p3frontend: %s: %w", name, err)
		}
		if !ok {
			continue
		}
		out = append(out, name)
	}
	sort.Strings(out)
	return out, nil
}
