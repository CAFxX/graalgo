def main():
    parts = [HEADER]
    for fn in FILES:
        with open(f"{GOROOT}/{fn}") as f:
            src = f.read()
        # Strip the package clause; imports are hoisted to the header.
        src = re.sub(r"^package cmplx\n", "", src, count=1, flags=re.M)
        src = re.sub(r'^import "math"\n', "", src, count=1, flags=re.M)
        src = re.sub(r'^import \(\n\t"math"\n\t"math/bits"\n\)\n', "", src, count=1, flags=re.M)
        if fn == "asin.go":
            assert ASIN_OLD in src, "Asin manualization anchor missing"
            src = src.replace(ASIN_OLD, ASIN_NEW)
            assert ASINH_OLD in src, "Asinh manualization anchor missing"
            src = src.replace(ASINH_OLD, ASINH_NEW)
        if fn == "sin.go":
            assert SINHCOSH_OLD in src, "sinhcosh anchor missing"
            src = src.replace(SINHCOSH_OLD, SINHCOSH_NEW)
            # Rewrite the 4 two-target call sites to the __-helper.
            n = src.count("sh, ch := sinhcosh(")
            assert n == 4, f"sinhcosh call sites: {n}"
            src = re.sub(
                r"sh, ch := sinhcosh\((imag\(x\)|real\(x\))\)",
                r"__sc := __cmplxSinhcosh(\1); sh, ch := __sc.sh, __sc.ch",
                src,
            )
            assert "sinhcosh(" not in src.replace("__cmplxSinhcosh(", "")
        if fn == "polar.go":
            assert POLAR_OLD in src, "Polar anchor missing"
            src = src.replace(POLAR_OLD, POLAR_NEW)
        parts.append(src.rstrip() + "\n\n")
    out = "".join(parts).rstrip() + "\n`\n"
    with open(os.path.join(OUTDIR, "synth_mathcmplx.go"), "w") as f:
        f.write(out)
    print("wrote synth_mathcmplx.go", len(out), "bytes")


main()
