type __lzwReaderReadPair struct {
	n int
	err error
}

func __lzwReaderRead(r *Reader, b []byte) __lzwReaderReadPair {

	for {
		if len(r.toRead) > 0 {
			n := copy(b, r.toRead)
			r.toRead = r.toRead[n:]
			return __lzwReaderReadPair{n: n, err: nil}
		}
		if r.err != nil {
			return __lzwReaderReadPair{n: 0, err: r.err}
		}
		r.decode()
	}
}

