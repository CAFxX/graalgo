// A ChaCha8 is a ChaCha8-based cryptographically strong
// random number generator.
type ChaCha8 struct {
	state __chacha8State

	// The last readLen bytes of readBuf are still to be consumed by Read.
	readBuf [8]byte
	readLen int // 0 <= readLen <= 8
}

// NewChaCha8 returns a new ChaCha8 seeded with the given seed.
func NewChaCha8(seed [32]byte) *ChaCha8 {
	c := new(ChaCha8)
	__chacha8Init(&c.state, seed)
	return c
}

// Seed resets the ChaCha8 to behave the same way as NewChaCha8(seed).
func (c *ChaCha8) Seed(seed [32]byte) {
	__chacha8Init(&c.state, seed)
	c.readLen = 0
	c.readBuf = [8]byte{}
}

// Uint64 returns a uniformly distributed random uint64 value.
func (c *ChaCha8) Uint64() uint64 {
	for {
		p := __chacha8Next(&c.state); x, ok := p.v, p.ok
		if ok {
			return x
		}
		__chacha8Refill(&c.state)
	}
}

// Read reads exactly len(p) bytes into p.
// It always returns len(p) and a nil error.
//
// If calls to Read and Uint64 are interleaved, the order in which bits are
// returned by the two is undefined, and Read may return bits generated before
// the last call to Uint64.
type __chacha8ReadPair struct {
	n int
	err error
}

func __chacha8Read(c *ChaCha8, p []byte) __chacha8ReadPair {
	var n int
	var err error
	if c.readLen > 0 {
		n = copy(p, c.readBuf[len(c.readBuf)-c.readLen:])
		c.readLen -= n
		p = p[n:]
	}
	for len(p) >= 8 {
		byteorder.LEPutUint64(p, c.Uint64())
		p = p[8:]
		n += 8
	}
	if len(p) > 0 {
		byteorder.LEPutUint64(c.readBuf[:], c.Uint64())
		n += copy(p, c.readBuf[:])
		c.readLen = 8 - len(p)
	}
	return __chacha8ReadPair{n: n, err: err}
}

func (c *ChaCha8) Read(p []byte) (n int, err error) {
	panic("math/rand/v2: ChaCha8.Read: multi-result desugar")
}

// UnmarshalBinary implements the [encoding.BinaryUnmarshaler] interface.
func (c *ChaCha8) UnmarshalBinary(data []byte) error {
	__cp := __cutPrefix(data, []byte("readbuf:")); data, ok := __cp.after, __cp.found
	if ok {
		var buf []byte
		__rp := __readUint8LengthPrefixed(data); buf, data, ok = __rp.buf, __rp.rest, __rp.ok
		if !ok {
			return errors.New("invalid ChaCha8 Read buffer encoding")
		}
		c.readLen = copy(c.readBuf[len(c.readBuf)-len(buf):], buf)
	}
	return __chacha8Unmarshal(&c.state, data)
}

type __cutPrefixPair struct {
	after []byte
	found bool
}

func __cutPrefix(s, prefix []byte) __cutPrefixPair {
	if len(s) < len(prefix) || string(s[:len(prefix)]) != string(prefix) {
		return __cutPrefixPair{after: s}
	}
	return __cutPrefixPair{after: s[len(prefix):], found: true}
}

type __readUint8LengthPrefixedPair struct {
	buf []byte
	rest []byte
	ok   bool
}

func __readUint8LengthPrefixed(b []byte) __readUint8LengthPrefixedPair {
	if len(b) == 0 || len(b) < int(1+b[0]) {
		return __readUint8LengthPrefixedPair{}
	}
	return __readUint8LengthPrefixedPair{buf: b[1 : 1+b[0]], rest: b[1+b[0]:], ok: true}
}

