package main

// Re-test trigger for the synthetic math package's accuracy contract
// (see gen_synth_math.py header and the ACCURACY CONTRACT in
// synth_math.go).
//
// TestSyntheticMathDifferential extracts syntheticMathSource from
// synth_math.go, remaps the six intrinsics (whose bodies panic by design --
// the exporter intercepts them into wire nodes) to the stdlib math
// equivalents, and runs the white-box differential driver
// (testdata/synthmath_diff/driver_test.go) asserting BIT-EXACTNESS vs gc
// on adversarial + random inputs.
//
// Re-run (and require green) when the Go toolchain, the JDK, or the
// generator changes. The Sqrt/FMA intrinsic claims additionally rest on
// JLS/spec correct-rounding guarantees; the Java-side nodes
// (MathSqrtNode/MathFmaNode) carry their own notes.

import (
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

func syntheticMathInnerSource(t *testing.T) string {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "synth_math.go", nil, 0)
	if err != nil {
		t.Fatalf("parsing synth_math.go: %v", err)
	}
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		for _, spec := range gd.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			for i, name := range vs.Names {
				if name.Name == "syntheticMathSource" && i < len(vs.Values) {
					lit, ok := vs.Values[i].(*ast.BasicLit)
					if !ok || lit.Kind != token.STRING {
						t.Fatalf("syntheticMathSource is not a string literal")
					}
					raw, err := strconv.Unquote(lit.Value)
					if err != nil {
						t.Fatalf("unquoting syntheticMathSource: %v", err)
					}
					return raw
				}
			}
		}
	}
	t.Fatalf("syntheticMathSource const not found in synth_math.go")
	return ""
}

// TestSyntheticMathGeneratorMarker pins the generator claim itself: the
// file must say it was generated by gen_synth_math.py (the drift gate in
// `make all` enforces generator<->file agreement; this pins the claim the
// gate enforces).
func TestSyntheticMathGeneratorMarker(t *testing.T) {
	raw, err := os.ReadFile("synth_math.go")
	if err != nil {
		t.Fatalf("reading synth_math.go: %v", err)
	}
	if !strings.Contains(string(raw),
		"Code generated by gen_synth_math.py from gc 1.27.1.") {
		t.Fatalf("synth_math.go does not name gen_synth_math.py as its generator")
	}
	if strings.Contains(string(raw), "assemble_synth.py") {
		t.Fatalf("synth_math.go still references the lost assemble_synth.py")
	}
	if strings.Contains(string(raw), "hidden_files/m7-math") {
		t.Fatalf("synth_math.go still references hidden_files/m7-math")
	}
}

func TestSyntheticMathDifferential(t *testing.T) {
	raw := syntheticMathInnerSource(t)

	// Remap the six intrinsics to stdlib math: their panic bodies never
	// run in production (exporter intercepts), and the differential
	// driver needs callable implementations. Sqrt/FMA map to the
	// correctly-rounded stdlib versions, matching the intrinsic claims.
	remaps := [][2]string{
		{`func Float32bits(f float32) uint32     { panic("math: intrinsic Float32bits") }`,
			`func Float32bits(f float32) uint32     { return math.Float32bits(f) }`},
		{`func Float32frombits(b uint32) float32 { panic("math: intrinsic Float32frombits") }`,
			`func Float32frombits(b uint32) float32 { return math.Float32frombits(b) }`},
		{`func Float64bits(f float64) uint64     { panic("math: intrinsic Float64bits") }`,
			`func Float64bits(f float64) uint64     { return math.Float64bits(f) }`},
		{`func Float64frombits(b uint64) float64 { panic("math: intrinsic Float64frombits") }`,
			`func Float64frombits(b uint64) float64 { return math.Float64frombits(b) }`},
		{`func Sqrt(x float64) float64       { panic("math: intrinsic Sqrt") }`,
			`func Sqrt(x float64) float64       { return math.Sqrt(x) }`},
		{`func FMA(x, y, z float64) float64 { panic("math: intrinsic FMA") }`,
			`func FMA(x, y, z float64) float64 { return math.FMA(x, y, z) }`},
	}
	for _, r := range remaps {
		if !strings.Contains(raw, r[0]) {
			t.Fatalf("intrinsic body not found for remap: %q", r[0][:60])
		}
		raw = strings.Replace(raw, r[0], r[1], 1)
	}
	raw = strings.Replace(raw, "package math\n", "package ms\nimport \"math\"\n", 1)

	dir := t.TempDir()
	msDir := filepath.Join(dir, "ms")
	if err := os.MkdirAll(msDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(msDir, "go.mod"),
		[]byte("module ms\n\ngo 1.24\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(msDir, "ms.go"), []byte(raw), 0o644); err != nil {
		t.Fatal(err)
	}
	driver, err := os.ReadFile("testdata/synthmath_diff/driver_test.go")
	if err != nil {
		t.Fatalf("reading driver_test.go: %v", err)
	}
	if err := os.WriteFile(filepath.Join(msDir, "driver_test.go"), driver, 0o644); err != nil {
		t.Fatal(err)
	}

	goBin := os.Getenv("GO")
	if goBin == "" {
		goBin = "go"
	}
	cmd := exec.Command(goBin, "test", "-count=1", "./...")
	cmd.Dir = msDir
	cmd.Env = append(os.Environ(),
		"GOFLAGS=-mod=mod",
		"GOTMPDIR="+filepath.Join(dir, "tmp"),
		"TMPDIR="+filepath.Join(dir, "tmp"),
	)
	if err := os.MkdirAll(filepath.Join(dir, "tmp"), 0o755); err != nil {
		t.Fatal(err)
	}
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("differential driver failed: %v\n%s", err, out)
	}
	t.Logf("differential driver green:\n%s", lastLines(string(out), 8))
}

func lastLines(s string, n int) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, "\n")
}
