#!/usr/bin/env python3
"""Generate the linkname provider/intrinsic tables (zz_linkname_tables.go).

Two mechanical scrapes, no hand lists (RV-P1-02, option (b)):

1. runtimeProvidedLinknames: every two-field `//go:linkname <local> <symbol>`
   directive in the build-filtered GOROOT runtime package (linux/amd64,
   `purego` + GRAALGO_BUILD_TAGS -- the same build context the exporter uses
   in diskimport.go). These are gc's own "bodyless in package P, provided by
   runtime" mechanism: the listed symbols are runtime services, not assembly.
   The frontend reroutes references to them onto the linkname path instead of
   the retired "unimplemented" stub.

2. linknameIntrinsicSymbols: every `Linknames.register("<symbol>", ...)` call
   in the backend's LinknameIntrinsics.java. The frontend rejects, at export
   time, any reference to a linkname function whose symbol is neither
   registered here nor provided by a compiled Go function (the Go->Go
   linkname arm).

Regenerated by `make gen-linkname-tables` (part of `make generate`); the
output is committed and CI-pinned via `git diff --exit-code` after
`make all`, so the tables can never silently drift from their sources.

Environment:
  GO               go binary to use (default: "go" on PATH). Must report
                   go1.27.1 -- the scrape reads that exact toolchain's
                   runtime sources; anything else fails fast.
  GRAALGO_GOROOT   GOROOT to scrape (default: `$GO env GOROOT`).
  GRAALGO_BUILD_TAGS extra build tags, space-separated (default: "").
"""

import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(HERE))
OUT_PATH = os.path.join(HERE, "zz_linkname_tables.go")

GO_VERSION_PIN = "go1.27.1"
LINKNAME_INTRINSICS = os.path.join(
    REPO_ROOT, "internal", "backend", "interop", "src", "main", "java",
    "graalgo", "p3link", "LinknameIntrinsics.java")

REGISTER_RE = re.compile(r'Linknames\.register\("((?:[^"\\]|\\.)*)"')


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        raise SystemExit("gen_linkname_tables: command failed: %s\n%s%s"
                         % (" ".join(cmd), r.stdout, r.stderr))
    return r.stdout


def java_unescape(s):
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append({"n": "\n", "t": "\t", "r": "\r", '"': '"',
                        "\\": "\\"}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def main():
    go = os.environ.get("GO", "go")
    version = run([go, "version"]).strip()
    if GO_VERSION_PIN not in version:
        raise SystemExit(
            "gen_linkname_tables: need %s, have %r (set GO=...)" %
            (GO_VERSION_PIN, version))
    goroot = os.environ.get("GRAALGO_GOROOT") or run(
        [go, "env", "GOROOT"]).strip()
    tags = ["purego"] + os.environ.get("GRAALGO_BUILD_TAGS", "").split()

    # Scrape 1: provider-side //go:linkname in the build-filtered runtime.
    files = run([go, "list", "-tags", ",".join(tags), "-f",
                 "{{range .GoFiles}}{{$.Dir}}/{{.}}\n{{end}}",
                 "runtime"],
                env={**os.environ, "GOFLAGS": ""}).split()
    files = [f for f in files if f.endswith(".go")]
    if not files:
        raise SystemExit("gen_linkname_tables: `go list runtime` returned no files")
    providers = {}
    for path in files:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if not line.startswith("//go:linkname "):
                    continue
                fields = line[len("//go:linkname "):].split()
                if len(fields) == 2:
                    # Two-field form: <local> provided here under <symbol>.
                    providers[fields[1]] = fields[1]
                # Single-field form is consumer-side (declared here,
                # implemented elsewhere); not a provider entry.
    if not providers:
        raise SystemExit("gen_linkname_tables: no provider directives scraped; "
                         "refusing to emit an empty table")

    # Scrape 2: registered backend linkname intrinsics.
    with open(LINKNAME_INTRINSICS, encoding="utf-8") as fh:
        java_src = fh.read()
    intrinsics = sorted({java_unescape(m.group(1))
                         for m in REGISTER_RE.finditer(java_src)})
    if not intrinsics:
        raise SystemExit("gen_linkname_tables: no Linknames.register calls "
                         "scraped; refusing to emit an empty table")

    with open(OUT_PATH, "w", encoding="utf-8") as out:
        out.write("// Code generated by gen_linkname_tables.py — DO NOT EDIT.\n")
        out.write("//\n")
        out.write("// Regenerate with `make gen-linkname-tables`. The tables are\n")
        out.write("// mechanical scrapes (RV-P1-02): provider-side //go:linkname\n")
        out.write("// directives from the %s runtime sources, and\n" % GO_VERSION_PIN)
        out.write("// Linknames.register calls from LinknameIntrinsics.java.\n")
        out.write("package main\n\n")
        out.write("// runtimeProvidedLinknames maps a linkname symbol \"pkg.Func\"\n")
        out.write("// to itself for every symbol the GOROOT runtime package\n")
        out.write("// provides via a provider-side //go:linkname directive\n")
        out.write("// (%d entries). A bodyless function P.F with P.F in this\n" % len(providers))
        out.write("// table is a runtime service, not assembly: the frontend\n")
        out.write("// emits it on the linkname path.\n")
        out.write("var runtimeProvidedLinknames = map[string]string{\n")
        for sym in sorted(providers):
            out.write("\t%s: %s,\n" % (json.dumps(sym), json.dumps(providers[sym])))
        out.write("}\n\n")
        out.write("// linknameIntrinsicSymbols is the set of linkname symbols\n")
        out.write("// with a registered backend intrinsic (%d entries,\n" % len(intrinsics))
        out.write("// scraped from LinknameIntrinsics.java). A reference to a\n")
        out.write("// linkname function whose symbol is neither in this set\n")
        out.write("// nor provided by a compiled Go function is rejected at\n")
        out.write("// export time [RV-P1-02].\n")
        out.write("var linknameIntrinsicSymbols = map[string]bool{\n")
        for sym in intrinsics:
            out.write("\t%s: true,\n" % json.dumps(sym))
        out.write("}\n")
    print("gen_linkname_tables: %d provider symbols, %d intrinsic symbols -> %s"
          % (len(providers), len(intrinsics), OUT_PATH))


if __name__ == "__main__":
    main()
